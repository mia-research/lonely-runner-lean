# Statistical tests: χ² and mutual information
# ============================================================================

def chi2_test(df1, df2, name1="observed", name2="null"):
    """
    χ² test comparing observed vs null distributions.
    Returns (chi2_stat, p_value, dof).
    """
    # Build contingency table: rows=values from df1, cols=values from df2
    vals1 = set(df1) | set(df2)
    vals2 = set(df1) | set(df2)  # same set for symmetry

    cont = {}
    for v in vals1:
        cont[v] = {}
        for w in vals2:
            cont[v][w] = 0

    for v, w in zip(df1, df2):
        if v in cont and w in cont[v]:
            cont[v][w] += 1

    # Convert to contingency table (array)
    rows = sorted(cont.keys())
    cols = sorted(cont[rows[0]].keys()) if rows else []

    table = np.array([[cont[r].get(c, 0) for c in cols] for r in rows])

    if table.size == 0:
        return 0, 1.0, 0

    chi2, p, dof, ex = chi2_contingency(table)
    return float(chi2), float(p), int(dof)


def mutual_info_test(X, Y):
    """
    Compute mutual information I(X;Y) between discrete X and Y.
    Returns MI normalized by H(Y) to get a sensitivity measure [0,1].
    """
    # MI = H(Y) - H(Y|X)
    # H(Y|X) = sum_x P(x) * H(Y | X=x)

    # Build joint distribution
    X = np.asarray(X, dtype=int)
    Y = np.asarray(Y, dtype=int)

    if len(X) != len(Y):
        raise ValueError("X and Y must have same length")

    n = len(X)
    if n == 0:
        return 0.0

    # Use sklearn's mutual_info_score (normalized to [0,1])
    # It computes I(X;Y) = sum_ij P(x_i, y_j) log(P(x_i,y_j) / (P(x_i)*P(y_j)))

    # For comparison, we'll use a normalized version:
    # MI_norm = MI / min(H(X), H(Y)) or MI / H(Y)

    mi_raw = mutual_info_score(X, Y)

    # Entropy of Y
    unique_y, counts_y = np.unique(Y, return_counts=True)
    p_y = counts_y / n
    h_y = -np.sum(p_y * np.log(p_y + 1e-10))

    # Normalized MI
    mi_norm = mi_raw / (h_y + 1e-10)

    return float(mi_norm), float(mi_raw)


