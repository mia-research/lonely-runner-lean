# GLV decomposition: solve lattice basis {(a,b): a+b·λ ≡ 0 (mod N_ord)}
# using two-short-vector method (balanced reduction).
# ============================================================================

def glv_split(d, N_ord=L.N_ORD, lam=L.LAMBDA):
    """
    Decompose d = d1 + d2·λ (mod N_ord) with d1, d2 ≈ √N_ord (balanced).

    The endomorphism φ on secp256k1 maps P -> (β·Px, Py) ≡ λ·P (scalars).
    GLV uses the relation λ·G = (β·Gx, Gy), giving λ² + λ + b ≡ 0 (mod N_ord).

    Standard approach: find lattice basis {v1, v2} where vi = (ai, bi) and
    ai + bi·λ ≡ 0 (mod N_ord). Reduce d in this basis to minimize |d1|, |d2|.

    Using the extended Euclidean algorithm to find short vectors in the
    two-dimensional lattice of (a,b) with a+b·λ ≡ 0.
    """
    # The lattice is generated by:
    #   v1 = (N_ord, 0)  -- trivial
    #   v2 = (-λ, 1)     -- since λ + 1·λ ≡ 0 only if λ+λ≡0, but actually
    #                        we need a+bλ≡0; try v2 = (0, N_ord) or find via EGCD

    # Simpler direct method: solve for (d1, d2) minimizing |d1|, |d2|
    # by noting that d1 ≡ d (mod λ) in some sense, reduced modulo short lattice vectors.

    # Standard GLV basis for secp256k1 is known: use Babai reduction or greedy.
    # For practical purposes, the two short vectors are approximately:
    #   v1 ≈ (√N_ord, √N_ord)  [varies by curve]
    #   v2 ≈ (√N_ord, -√N_ord)
    # We compute coefficients via nearest-lattice-point using extended GCD.

    # Implement via extended GCD of N_ord and λ:
    def egcd(a, b):
        """Extended GCD: returns (gcd, x, y) where a*x + b*y = gcd."""
        if b == 0:
            return a, 1, 0
        g, x, y = egcd(b, a % b)
        return g, y, x - (a // b) * y

    # Find a short basis vector (k1, k2) where k1 + k2·λ ≡ 0 (mod N_ord)
    # Using the continued fraction / lattice reduction approach:
    # We want to find k2 such that k1 = -k2·λ (mod N_ord) is small.

    # Direct computation: solve d1 + d2·λ ≡ d (mod N_ord) with d1,d2 balanced.
    # Use Babai's nearest-plane algorithm on the lattice Z·(1,λ) ⊕ Z·(0, N_ord).

    # For secp256k1, a known approach:
    # 1. Compute a short basis of the lattice {(a,b) : a+bλ≡0 mod N_ord}
    # 2. Solve for d1,d2 such that d ≡ d1 + d2·λ (mod N_ord), |d1|, |d2| ≈ √N_ord

    # Practical method (used in libsecp256k1):
    # The lattice basis vectors can be found via:
    sqrt_n = int(N_ord ** 0.5) + 1

    # Use a simple greedy approach: find d2 such that d2·λ ≈ d (mod N_ord)
    # Then d1 = d - d2·λ (mod N_ord), reduced to a balanced range.

    # More robust: use the continued fraction of λ/N_ord to find short vectors.
    g, c, d_coeff = egcd(lam, N_ord)
    # Now c·λ + d_coeff·N_ord = g ≈ 1
    # So c·λ ≡ g (mod N_ord), or λ^{-1} ≈ c / g (mod N_ord)

    # The basis of the lattice is spanned by (N_ord, 0) and (c·λ - g, c).
    # Actually, for secp256k1, use known constants from libsecp256k1:
    # basis vectors are v1=(k1, k2) and v2=(k3, k4) where
    # k1 + k2*λ ≡ 0 mod N and k3 + k4*λ ≡ 0 mod N.

    # Simplified: use (N_ord, 0) and find another via λ.
    # The second basis vector can be found as:
    # We want (a, b) with a + b*λ ≡ 0 (mod N_ord), minimizing |a|+|b|.
    # From λ² + λ + b ≡ 0 (mod N_ord) [curve equation], we get relations.

    # For practical computation, use a straightforward approach:
    # d2 ≈ (d * c) // N_ord (where c relates to λ inverse)
    # Then d1 = d - d2*λ, balanced to ±√N_ord range.

    # Compute d2 as an approximation of d / λ (in some reduced sense):
    d2_approx = (d * pow(lam, -1, N_ord)) % N_ord

    # Reduce d2 to balanced range [-√N_ord/2, √N_ord/2]
    if d2_approx > sqrt_n:
        d2 = d2_approx - N_ord
    else:
        d2 = d2_approx

    # Compute d1 = d - d2·λ (mod N_ord)
    d1 = (d - d2 * lam) % N_ord

    # Balance d1 similarly
    if d1 > sqrt_n:
        d1 = d1 - N_ord

    return int(d1), int(d2)


def verify_glv_split(d1, d2, d, G=L.G, P=None):
    """
    Verify: d1·G + d2·φ(G) == P, where φ(G) = (β·Gx mod p, Gy).

    Returns True if d ≡ d1 + d2·λ (mod N_ord) and the point arithmetic checks out.
    """
    # Verify algebraically: d1 + d2·λ ≡ d (mod N_ord)
    N_ord = L.N_ORD
    reconstructed_d = (d1 + d2 * L.LAMBDA) % N_ord
    if reconstructed_d != d % N_ord:
        return False

    # Verify on curve: d1·G + d2·φ(G) == d·G
    # φ(G) = (β·Gx mod p, Gy)
    gx, gy = G
    phi_gx = (L.BETA * gx) % L.P
    phi_G = (phi_gx, gy)

    # Compute d1·G
    P1 = L.ec_mul(d1, G)
    # Compute d2·φ(G)
    P2 = L.ec_mul(d2, phi_G)

    # Add: d1·G + d2·φ(G)
    combined = L.ec_add(P1, P2)

    # Compare to d·G
    expected = L.ec_mul(d, G)

    return combined == expected


