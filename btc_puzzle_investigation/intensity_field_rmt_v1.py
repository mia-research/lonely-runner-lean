def isprime(m):
    if m < 2:
        return False
    for d in range(2, int(m**0.5) + 1):
        if m % d == 0:
            return False
    return True


def build_field(p, b=7):
    r = curve_orbit(p, b)
    if r is None:
        return None
    X, Y, n = r
    if (n - (p + 1))**2 > 4*p or not isprime(n):
        return None
    X = np.asarray(X, dtype=np.int64) % p
    # T(a,b) = sum_d e_p(b x_d) e_n(a d): for each b, an FFT over d
    W = np.exp(2j*np.pi*np.outer(np.arange(p), X)/p)      # (p, n) : rows b, cols d
    T = np.fft.fft(W, axis=1)                              # (p, n) : T[b, a]
    I = np.abs(T)**2
    I = I / I.mean()
    return n, I, X


def orbit_labels(n, p, lam, beta):
    """orbits of (a,b) in Z/n x Z/p under <(a,b)->(-a,b), (a,b)->(a,-b), (a,b)->(lam a, beta b)>."""
    lab = -np.ones((p, n), dtype=np.int64)                 # indexed [b, a]
    cur = 0
    for b0 in range(p):
        for a0 in range(n):
            if lab[b0, a0] >= 0:
                continue
            stack = [(a0, b0)]
            while stack:
                a, bb = stack.pop()
                if lab[bb, a] >= 0:
                    continue
                lab[bb, a] = cur
                stack.append(((-a) % n, bb))
                stack.append((a, (-bb) % p))
                stack.append(((a*lam) % n, (bb*beta) % p))
            cur += 1
    return lab, cur


def stats(I):
    """spatial statistics of the intensity field."""
    a1 = float(np.mean(I*np.roll(I, 1, axis=1)))           # lag 1 in a
    b1 = float(np.mean(I*np.roll(I, 1, axis=0)))           # lag 1 in b
    a3 = float(np.mean(I*np.roll(I, 3, axis=1)))
    exc = (I > 1.0).astype(np.float64)
    k = 8
    pb, na = I.shape
    nb0, na0 = pb//k, na//k
    blk = exc[:nb0*k, :na0*k].reshape(nb0, k, na0, k).sum(axis=(1, 3))
    nv = float(blk.var())
    return {"C_a1": a1, "C_b1": b1, "C_a3": a3, "NumVar": nv}


KEYS = ["C_a1", "C_b1", "C_a3", "NumVar"]


