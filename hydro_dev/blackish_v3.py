#!/usr/bin/env python3
"""Blackish v3 -- short replies and an automatic axiom gate.

A layer over the v2 warm-LSP bridge
(`same_origin_hydro_lean_4_bridge_v2_warm_lsp_tactic_ladder.py`, loaded by path
and left unmodified). Everything v2 does is kept: the warm `lean --server`
slots, the CLI fallback, the deny-list, no CORS headers.

What v3 changes
---------------
1. AXIOM GATE (applies to every verdict, including `/tactics`).
   v2 reports `verified` when there are no errors and no `sorry`. A file that
   declares `axiom foo : False` and uses it passes that test unless the caller
   wrote `#print axioms` and read the result. v3 appends `#print axioms <name>`
   for every `theorem` / `lemma` / `def` / `abbrev` it can name in the
   submission and reports `verified` only when every footprint lies inside the
   allowed set (default: propext, Classical.choice, Quot.sound).
   Fail closed: if an appended `#print axioms` line does not elaborate, the
   verdict is `verified: false` with the declaration named. A submission that
   itself declares an `axiom` is refused even when no named declaration uses
   it, because an `example` could (start with `--allow-axiom NAME` to permit
   a specific one).

   What the gate does NOT see (reported, never silently passed over):
     - `example` blocks (they have no name to print); counted in
       `axioms.unnamed_examples`.
     - declarations generated by macros or attributes (`to_additive`, etc.) and
       anonymous instances.
   The name scan is a line regex over comment-stripped source with a
   namespace/section stack. It is a parser of convenience, not Lean's parser.

2. SHORT REPLIES on `POST /verify` (default).
   Verdict, a one-line reason, the axiom summary, and the first few errors
   (truncated). No raw stdout/stderr. Ask for the old shape with
   `"detail": "full"` in the request body.
   `POST /` keeps the full v2-shaped reply, because the bundled Black UI posts
   there and reads `stdout` / `stderr`. The gate still applies to it.

3. `/health` reports `service: blackish` and `version`, as
   DELEGATION_ZERO_TOKEN.md section 1.2 tells runners to expect, plus v2's
   fields.

Line numbers in errors refer to the caller's source: the gate's lines are
appended after it.

Run (from anywhere; `--cwd` picks the Lake project):
    python3 -I hydro_dev/blackish_v3.py --port 8089 \
        --cwd "/Users/trentpalelei/Desktop/Math Ex/LonelyRunner"
"""

import argparse
import importlib.util
import json
import os
import re
import subprocess
import threading
import time
from http.server import ThreadingHTTPServer

VERSION = "3.0.0"
HERE = os.path.dirname(os.path.abspath(__file__))
V2_PATH = os.path.join(
    HERE, "same_origin_hydro_lean_4_bridge_v2_warm_lsp_tactic_ladder.py"
)

_spec = importlib.util.spec_from_file_location("hydro_bridge_v2", V2_PATH)
v2 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(v2)

STANDARD_AXIOMS = ("propext", "Classical.choice", "Quot.sound")
ALLOWED_AXIOMS = set(STANDARD_AXIOMS)

MAX_ERRORS_DEFAULT = 3
ERROR_CHARS_DEFAULT = 600

# -----------------------------------------------------------------------------
# Name scan: which declarations can be handed to `#print axioms`
# -----------------------------------------------------------------------------
_NAME = r"((?:«[^»]*»|[^\s:({\[⦃«])+)"
_MODS = r"(?:(?:private|protected|noncomputable|nonrec|public|partial)\s+)*"
_ATTRS = r"(?:@\[[^\]]*\]\s*)*"
_DECL_RE = re.compile(
    r"^\s*" + _ATTRS + _MODS + r"(theorem|lemma|def|abbrev)\s+" + _NAME
)
_EXAMPLE_RE = re.compile(r"^\s*" + _ATTRS + _MODS + r"example\b")
_NS_RE = re.compile(r"^\s*namespace\s+(\S+)\s*$")
_SEC_RE = re.compile(r"^\s*(?:noncomputable\s+)?(?:section|mutual)\b")
_END_RE = re.compile(r"^\s*end(?:\s+\S+)?\s*$")
_AXIOM_DECL_RE = re.compile(r"^\s*" + _ATTRS + _MODS + r"axiom\s+" + _NAME)


def scan_declarations(code: str) -> dict:
    """Return fully qualified names to print, declared axioms, example count."""
    scrubbed = v2.strip_lean_comments(code)
    stack = []  # entries: namespace name (str) or None for section/mutual
    names, declared_axioms, examples = [], [], 0

    def qualify(raw: str) -> str:
        if raw.startswith("_root_."):
            return raw[len("_root_."):]
        prefix = ".".join(s for s in stack if s)
        return prefix + "." + raw if prefix else raw

    for line in scrubbed.splitlines():
        m = _NS_RE.match(line)
        if m:
            stack.append(m.group(1))
            continue
        if _SEC_RE.match(line):
            stack.append(None)
            continue
        if _END_RE.match(line):
            if stack:
                stack.pop()
            continue
        m = _DECL_RE.match(line)
        if m:
            # `theorem foo.{u}` leaves a trailing dot once the regex stops at `{`
            q = qualify(m.group(2).rstrip("."))
            if q and q not in names:
                names.append(q)
            continue
        m = _AXIOM_DECL_RE.match(line)
        if m:
            declared_axioms.append(qualify(m.group(1)))
            continue
        if _EXAMPLE_RE.match(line):
            examples += 1
    return {"names": names, "declared_axioms": declared_axioms, "examples": examples}


# -----------------------------------------------------------------------------
# Diagnostics: one entry per message, with the caller's line number
# -----------------------------------------------------------------------------
_DIAG_HEAD = re.compile(r"^(?:.*?:)?(\d+):(\d+): (error|warning|info)\b")


def diagnostics_from(res: dict) -> list:
    """Normalise both engines to [{line, col, severity, text}].

    The warm engine already returns whole messages as `line:col: sev: text`.
    The CLI engine returns only header lines in `errors`, so its raw output is
    re-split here to recover message bodies (goal states).
    """
    out = []
    if str(res.get("engine", "")).startswith("lsp"):
        for sev, key in (("error", "errors"), ("warning", "warnings")):
            for item in res.get(key) or []:
                m = _DIAG_HEAD.match(item)
                out.append({
                    "line": int(m.group(1)) if m else 0,
                    "col": int(m.group(2)) if m else 0,
                    "severity": sev,
                    "text": item,
                })
        return out

    raw = (res.get("raw_stdout") or "") + "\n" + (res.get("raw_stderr") or "")
    cur = None
    for line in raw.splitlines():
        m = _DIAG_HEAD.match(line)
        if m:
            if cur:
                out.append(cur)
            # drop the temp-file path so the text reads `line:col: sev: ...`
            text = line[m.start(1):]
            cur = {
                "line": int(m.group(1)), "col": int(m.group(2)),
                "severity": m.group(3), "text": text,
            }
        elif re.match(r"^'.*' (?:depends on axioms|does not depend on any axioms)", line):
            # unpositioned `#print axioms` output ends the preceding message
            if cur:
                out.append(cur)
            cur = None
        elif cur is not None:
            cur["text"] += "\n" + line
    if cur:
        out.append(cur)
    if not out:
        # timeouts and engine failures carry no positions
        for item in res.get("errors") or []:
            out.append({"line": 0, "col": 0, "severity": "error", "text": item})
    return [d for d in out if d["severity"] in ("error", "warning")]


# -----------------------------------------------------------------------------
# The gated check
# -----------------------------------------------------------------------------
def gated_check(code: str, timeout_sec: float = 120.0) -> dict:
    """Run v2's check on `code` plus appended `#print axioms`, then gate."""
    scan = scan_declarations(code)
    # A leading blank line guarantees the first appended command starts on its
    # own line whether or not the source ends with a newline.
    gate_lines = ["#print axioms " + n for n in scan["names"]]
    full_code = code.rstrip("\n") + "\n" + "\n".join(gate_lines) + "\n"
    user_lines = len(code.rstrip("\n").splitlines())

    res = v2.check_with_kernel(full_code, timeout_sec=timeout_sec)
    diags = diagnostics_from(res)

    user_errors, gate_failed = [], []
    for d in diags:
        if d["severity"] != "error":
            continue
        idx = d["line"] - user_lines - 1
        if d["line"] > user_lines and 0 <= idx < len(scan["names"]):
            gate_failed.append(scan["names"][idx])
        else:
            user_errors.append(d)
    warnings = [d for d in diags if d["severity"] == "warning"]

    profiles = {}
    for p in res.get("axioms") or []:
        profiles.setdefault(p["decl"], [])
        for a in p["axioms"]:
            if a not in profiles[p["decl"]]:
                profiles[p["decl"]].append(a)
    nonstandard = {
        decl: [a for a in axs if a not in ALLOWED_AXIOMS]
        for decl, axs in profiles.items()
    }
    nonstandard = {d: a for d, a in nonstandard.items() if a}

    has_sorry = bool(res.get("sorryAx_count"))
    compiled = not user_errors and res.get("return_code") in (0, 1) and (
        res.get("success") or bool(gate_failed)
    )
    # `compiled` is about the caller's source only: an appended line that fails
    # must not be reported as a compile error in their code, but it does block
    # `verified` below.
    if res.get("return_code") not in (0, 1):
        compiled = False

    if not compiled:
        reason = "compile errors" if user_errors else "engine failure or timeout"
    elif has_sorry:
        reason = "sorry present"
    elif nonstandard:
        reason = "non-standard axioms: " + ", ".join(
            sorted({a for axs in nonstandard.values() for a in axs})
        )
    elif gate_failed:
        reason = "axiom check did not elaborate for: " + ", ".join(gate_failed)
    elif [a for a in scan["declared_axioms"] if a not in ALLOWED_AXIOMS]:
        # An axiom used only inside an `example` has no footprint to print, so
        # a submission that declares one is refused outright.
        reason = "submission declares axioms: " + ", ".join(scan["declared_axioms"])
    else:
        reason = "ok"

    verified = reason == "ok"
    gate = {
        "allowed": sorted(ALLOWED_AXIOMS),
        "checked": [n for n in scan["names"] if n not in gate_failed],
        "unchecked": gate_failed,
        "nonstandard": nonstandard,
        "declared_axioms": scan["declared_axioms"],
        "unnamed_examples": scan["examples"],
        "used": sorted({a for axs in profiles.values() for a in axs}),
    }
    return {
        "verified": verified,
        "compiled": compiled,
        "reason": reason,
        "engine": res.get("engine", "unknown"),
        "gate": gate,
        "user_errors": user_errors,
        "warnings": warnings,
        "raw": res,
    }


def brief_reply(g: dict, max_errors: int, error_chars: int) -> dict:
    errs = g["user_errors"]
    shown = []
    for d in errs[:max_errors]:
        t = d["text"]
        if len(t) > error_chars:
            t = t[:error_chars] + " ...[truncated %d chars]" % (len(d["text"]) - error_chars)
        shown.append(t)
    gate = g["gate"]
    axioms = {
        "used": gate["used"],
        "checked": len(gate["checked"]),
        "unnamed_examples": gate["unnamed_examples"],
    }
    # Only carry the fields that say something.
    for key in ("unchecked", "nonstandard", "declared_axioms"):
        if gate[key]:
            axioms[key] = gate[key]
    out = {
        "verified": g["verified"],
        "reason": g["reason"],
        "axioms": axioms,
        "error_count": len(errs),
        "warning_count": len(g["warnings"]),
        "engine": g["engine"],
    }
    if shown:
        out["errors"] = shown
    return out


def full_reply(g: dict) -> dict:
    """v2-shaped reply (the Black UI reads this) with the gate applied."""
    res = dict(g["raw"])
    res["verified"] = g["verified"]
    res["reason"] = g["reason"]
    res["gate"] = g["gate"]
    if g["reason"].startswith(("non-standard", "axiom check", "submission declares")):
        # Surface the gate's refusal where the UI already looks.
        note = "blackish gate: " + g["reason"]
        res["errors"] = list(res.get("errors") or []) + [note]
        res["stderr"] = ((res.get("stderr") or "") + "\n" + note).strip()
        res["raw_stderr"] = ((res.get("raw_stderr") or "") + "\n" + note).strip()
    return res


# -----------------------------------------------------------------------------
# HTTP
# -----------------------------------------------------------------------------
MAX_BODY = 1_048_576


class Handler(v2.Handler):
    def do_GET(self):
        if self.path == "/health":
            pool = v2.LSP_POOL
            self._json(200, {
                "service": "blackish",
                "version": VERSION,
                "status": "ok",
                "repo": v2.LEAN_CWD,
                "lean_cwd": v2.LEAN_CWD,
                "warm_import_slots": len(pool.open_docs) if pool is not None else 0,
                "allowed_axioms": sorted(ALLOWED_AXIOMS),
                "endpoints": ["/verify", "/tactics", "/health"],
            })
            return
        super().do_GET()

    def _read_json(self):
        n = int(self.headers.get("Content-Length", 0))
        if n > MAX_BODY:
            self._json(413, {"verified": False, "reason": "request too large"})
            return None
        try:
            req = json.loads(self.rfile.read(n).decode("utf-8"))
        except Exception as e:
            self._json(400, {"verified": False, "reason": "bad json: %s" % e})
            return None
        if not isinstance(req, dict) or not isinstance(req.get("code", ""), str):
            self._json(400, {"verified": False, "reason": "body must be {\"code\": str}"})
            return None
        return req

    def do_POST(self):
        req = self._read_json()
        if req is None:
            return
        if self.path == "/tactics":
            self._tactics(req)
            return
        self._verify(req, brief_default=(self.path == "/verify"))

    def _verify(self, req, brief_default):
        code = req.get("code", "")
        detail = req.get("detail") or ("brief" if brief_default else "full")
        t0 = time.time()
        forbidden = v2.check_deny_list(code)
        if forbidden:
            msg = "rejected: forbidden construct (%s)" % forbidden
            if detail == "full":
                self._json(200, {
                    "success": False, "verified": False, "reason": msg,
                    "errors": [msg], "warnings": [], "axioms": [],
                    "sorryAx": 0, "sorryAx_count": 0,
                    "raw_stdout": "", "raw_stderr": msg, "stdout": "", "stderr": msg,
                })
            else:
                self._json(200, {"verified": False, "reason": msg})
            return
        try:
            g = gated_check(code, timeout_sec=120.0)
        except subprocess.TimeoutExpired:
            self._json(200, {"verified": False, "reason": "timeout 120s"})
            return
        except Exception as e:
            self._json(200, {"verified": False, "reason": "bridge error: %s" % e})
            return
        elapsed = round((time.time() - t0) * 1000.0, 1)
        if detail == "full":
            out = full_reply(g)
        else:
            out = brief_reply(
                g,
                int(req.get("max_errors", MAX_ERRORS_DEFAULT)),
                int(req.get("error_chars", ERROR_CHARS_DEFAULT)),
            )
        out["elapsed_ms"] = elapsed
        self._json(200, out)

    def _tactics(self, req):
        code = req.get("code", "")
        if "sorry" not in code:
            self._json(200, {"found": False, "reason": "no sorry in input"})
            return
        forbidden = v2.check_deny_list(code)
        if forbidden:
            self._json(200, {"found": False, "reason": "forbidden construct (%s)" % forbidden})
            return
        custom = req.get("ladder")
        if isinstance(custom, list) and custom and all(
            isinstance(t, str) and re.match(r"^[A-Za-z0-9_!.?\s]+$", t) for t in custom
        ):
            ladder = custom
        else:
            ladder = v2.LADDER

        attempts, winner = [], None
        t0 = time.time()
        for tac in ladder:
            variant = v2.replace_first_sorry_tactic(code, tac)
            if variant == code:
                self._json(200, {"found": False,
                                 "reason": "could not locate ':= by sorry' pattern"})
                return
            t_rung = time.time()
            try:
                g = gated_check(variant, timeout_sec=35.0)
                ok, why = g["verified"], g["reason"]
            except Exception as e:
                ok, why = False, "bridge error: %s" % e
            attempts.append({
                "tactic": tac, "ok": ok, "reason": why,
                "rung_ms": round((time.time() - t_rung) * 1000.0, 1),
            })
            if ok:
                winner = {"tactic": tac, "code": variant}
                break
        out = {
            "found": winner is not None,
            "tactic": winner and winner["tactic"],
            "attempts": attempts,
            "total_ms": round((time.time() - t0) * 1000.0, 1),
        }
        # The winning source repeats the caller's input; return it on request.
        if winner and req.get("detail") == "full":
            out["code"] = winner["code"]
        self._json(200, out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Blackish v3 (brief replies, axiom gate)")
    parser.add_argument("--port", type=int, default=8089,
                        help="Port on 127.0.0.1 (default 8089; v2 holds 8088)")
    parser.add_argument("--cwd", default=None, help="Lean Lake project root")
    parser.add_argument("--ui-dir", default=HERE, help="Static UI directory")
    parser.add_argument("--no-lsp", action="store_true", help="Force cold CLI mode")
    parser.add_argument("--no-prewarm", action="store_true", help="Skip boot prewarm")
    parser.add_argument("--allow-axiom", action="append", default=[],
                        help="Extra axiom name to allow (repeatable)")
    args = parser.parse_args()

    if args.cwd:
        v2.LEAN_CWD = os.path.abspath(args.cwd)
    v2.UI_DIR = args.ui_dir
    ALLOWED_AXIOMS.update(args.allow_axiom)

    if not args.no_lsp:
        v2.LSP_POOL = v2.PersistentLeanLspServer(v2.LEAN_CWD)
        if not args.no_prewarm:
            threading.Thread(target=v2.LSP_POOL.prewarm_default_imports,
                             daemon=True).start()

    print("[*] Blackish v%s on http://127.0.0.1:%d -- repo: %s -- allowed axioms: %s"
          % (VERSION, args.port, v2.LEAN_CWD, sorted(ALLOWED_AXIOMS)), flush=True)
    ThreadingHTTPServer(("127.0.0.1", args.port), Handler).serve_forever()
