r"""
rt_lattice_v1 -- the exact limit of o on EVERY low-height resonance class.

The point.  o(e) is governed by the resonance lattice  L(e) = { n in Z^4 : n.e = 0 }.
Only the LOW part of L matters at leading order, and the classes are indexed by the
saturated sublattice generated by the resonances of height <= R.  This script computes,
exactly, the Haar average of the good indicator over the subtorus of every such class:

    rank 0 : no resonance of height <= R                 -> 3/32
    rank 1 : L_low = <n0>                                -> rt_limit_v2.rank1_limit
    rank 2 : L_low = <n1, n2> saturated                  -> rt_limit_v2.rank2_limit

and cross-validates each against the EXACT o of genuine deep members of the class.

usage:  python3 rt_lattice_v1.py [R] [PMAX]
"""
import sys, itertools
from fractions import Fraction as F
from math import gcd
from functools import reduce

import rt_limit_v2 as RL
import rt_limit_v1 as RL1
from ob_fast_v1 import o_fast, audit

R = int(sys.argv[1]) if len(sys.argv) > 1 else 3
PMAX = int(sys.argv[2]) if len(sys.argv) > 2 else 30
THIRD = F(1, 3)

print("=" * 80)
print("SELF-CHECK 1: general rank-1 routine vs the +-1-entry routine of rt_limit_v1")
print("=" * 80)
bad = n = 0
for v in itertools.product(range(-R, R + 1), repeat=4):
    if not RL.admissible(v) or not any(abs(x) == 1 for x in v):
        continue
    n += 1
    if RL.rank1_limit(v) != RL1.rank1_limit(v):
        bad += 1
        print("   MISMATCH", v, RL.rank1_limit(v), RL1.rank1_limit(v))
print(f"   {n} vectors compared, mismatches {bad}")

print()
print("=" * 80)
print(f"RANK-1 CLASSES, all admissible primitive n with ||n||_inf <= {R} (no +-1 needed)")
print("=" * 80)
seen1 = {}
for v in itertools.product(range(-R, R + 1), repeat=4):
    if not RL.admissible(v):
        continue
    k, rk = RL.lattice_key([list(v)])
    if k in seen1:
        continue
    ws = RL.witnesses([list(v)], PMAX=PMAX, want=1)
    if not ws:
        continue
    seen1[k] = (v, RL.rank1_limit(v), ws[0])
rows = sorted(seen1.values(), key=lambda t: -t[1])
print(f"   distinct realisable rank-1 classes: {len(rows)}")
for v, L, w in rows[:12]:
    print(f"      n0 = {str(v):>18}  o_inf = {str(L):>10} = {float(L):.6f}   witness {w}")
mx1 = max(L for _, L, _ in rows)
print(f"   MAX rank-1 limit = {mx1} = {float(mx1):.6f}    "
      f"exceeding 1/3: {sum(1 for _, L, _ in rows if L > THIRD)}")

print()
print("=" * 80)
print(f"RANK-2 CLASSES spanned by two admissible vectors with ||n||_inf <= {R}")
print("=" * 80)
adm = [v for v in itertools.product(range(-R, R + 1), repeat=4) if RL.admissible(v)]
print(f"   admissible height-<= {R} vectors: {len(adm)}")
seen2 = {}
for i in range(len(adm)):
    for j in range(i + 1, len(adm)):
        M = [list(adm[i]), list(adm[j])]
        B, rk = RL.kernel_basis(M)
        if rk != 2:
            continue
        k, _ = RL.lattice_key(M)
        if k in seen2:
            continue
        ws = RL.witnesses(M, PMAX=PMAX, want=4)
        if not ws:
            continue
        seen2[k] = (k, RL.rank2_limit(M), ws)
rows2 = sorted(seen2.values(), key=lambda t: -t[1])
print(f"   distinct realisable rank-2 classes: {len(rows2)}")
print()
print(f"   {'saturated lattice basis (HNF rows)':>44} {'o_inf':>12} {'float':>9}  witnesses")
for k, L, ws in rows2:
    flag = "   <-- EXCEEDS 1/3" if L > THIRD else ""
    print(f"   {str(k):>44} {str(L):>12} {float(L):>9.6f}  {ws[:2]}{flag}")
mx2 = max(L for _, L, _ in rows2) if rows2 else F(0)
print()
print(f"   MAX rank-2 limit = {mx2} = {float(mx2):.6f}    "
      f"exceeding 1/3: {sum(1 for _, L, _ in rows2 if L > THIRD)}")

print()
print("=" * 80)
print("SELF-CHECK 2: exact o of deep class members vs the class limit")
print("=" * 80)
print("   (o is computed exactly by ob_fast_v1; boundary audit reported)")
for k, L, ws in rows2[:8]:
    ws2 = [w for w in ws]
    print(f"   class {k}  o_inf = {L} = {float(L):.6f}")
    for w in ws2[:4]:
        ov = o_fast(w)
        a = audit(w)
        print(f"      e = {str(w):>26}  o = {str(ov):>18} = {float(ov):.6f}  "
              f"o - o_inf = {float(ov - L):+.3e}   audit {a}")
