r"""
tb_hunt_v2 -- the targeted search for a violation of (H3u), by CLASS not by tuple.

    (H3u)   Tail_3(e) = o(e) - o_inf(sat L_3(e))  <=  1/12   whenever rank L_3(e) <= 2.

PRE-DECLARED MECHANISM (stated before any data was looked at).  Tail_3 is
asymptotically a DIFFERENCE OF TWO CLASS LIMITS.  Let M' be a saturated sublattice
of Z^4 of rank <= 2 that is REALISABLE (some positive primitive e with
e_rho = rho mod 8 has n.e = 0 for every n in M'), and set

    M_3(M') := saturation of the subgroup generated by the height-<=3 vectors of M',
    Delta(M') := o_inf(M') - o_inf(M_3(M')).

A member e of the class whose own extra resonances all have large height has
o(e) close to o_inf(M') while sat L_3(e) = M_3(M') is unchanged, so

        limsup over the class of Tail_3  =  Delta(M') .

Hence Delta(M') > 1/12 on a realisable M' means (H3u) is FALSE, with an explicit
witness obtainable by going deep in that class.

Because M' is saturated and M_3(M') is saturated, rank M_3 = 2 forces M_3 = M' and
Delta = 0.  So only planes whose height-<=3 part has rank <= 1 can violate, and the
enumeration is organised around that:

   arm A (sub3 rank 1) : planes spanned by an admissible height-<=3 vector and a
                         second admissible vector of height <= HMAX;
   arm B (sub3 rank 0) : planes spanned by two admissible vectors of height in
                         [4, HMAX] that contain NO admissible height-<=3 vector.

Deduplication is by exact Plucker coordinates (O(1) per pair).  All limits are exact
Fractions (rt_limit_v2); heights, Plucker keys and membership tests are integer.

POPULATION LABELS (requirement (iii)).  This is a PARAMETER-box enumeration in two
senses and neither is a speed box: (1) generators range over the sup-norm-height box
||n||_inf <= HMAX; (2) witnesses e = B alpha range over the coefficient box
|alpha_i| <= PMAX, so the maximum speed actually reached is reported, not assumed.

usage:  python3 tb_hunt_v2.py [HMAX] [PMAX]
"""
import sys, itertools
from fractions import Fraction as F
from math import gcd
from functools import reduce

import rt_limit_v2 as RL

HMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 4
PMAX = int(sys.argv[2]) if len(sys.argv) > 2 else 40
PMAX1 = int(sys.argv[3]) if len(sys.argv) > 3 else 10   # rank-1 kernel is 3-dim
RHO = (1, 3, 5, 7)
BUDGET = F(1, 12)
FLOOR = F(3, 32)

TRIPLES = [(i, j, k) for i in range(4) for j in range(i + 1, 4)
           for k in range(j + 1, 4)]
PAIRIDX = [(i, j) for i in range(4) for j in range(i + 1, 4)]   # 01 02 03 12 13 23


def plucker(u, v):
    p = tuple(u[i] * v[j] - u[j] * v[i] for (i, j) in PAIRIDX)
    if not any(p):
        return None
    g = reduce(gcd, [abs(x) for x in p])
    p = tuple(x // g for x in p)
    for x in p:
        if x:
            if x < 0:
                p = tuple(-y for y in p)
            break
    return p


def in_plane(p, v):
    """v lies in the 2-plane with (normalised) Plucker vector p."""
    d = dict(zip(PAIRIDX, p))
    for (i, j, k) in TRIPLES:
        if d[(i, j)] * v[k] - d[(i, k)] * v[j] + d[(j, k)] * v[i] != 0:
            return False
    return True


CELLCAP = 120_000


def cell_count(rows):
    """number of floor-cells rt_limit_v2.rank2_limit would enumerate for this lattice."""
    B, rk = RL.kernel_basis([list(r) for r in rows])
    if rk != 2:
        return None
    size = 1
    for r in range(4):
        c1, c2 = B[r][0], B[r][1]
        size *= (max(0, c1) + max(0, c2)) - (min(0, c1) + min(0, c2)) + 1
    return size


def limit_of_rows(rows):
    if not rows:
        return FLOOR
    if len(rows) == 1:
        return RL.rank1_limit(tuple(rows[0]))
    return RL.rank2_limit(rows)


if __name__ == "__main__":
    print(f"tb_hunt_v2   HMAX = {HMAX}  PMAX = {PMAX}  PMAX1 = {PMAX1}")
    print(f"a realisable class with Delta > 1/12 = {float(BUDGET):.7f} refutes (H3u)\n")

    ADM = {}
    for H in (3, HMAX):
        ADM[H] = [v for v in itertools.product(range(-H, H + 1), repeat=4)
                  if RL.admissible(v)]
    ADM3, ADMH = ADM[3], ADM[HMAX]
    HIGH = [v for v in ADMH if max(abs(x) for x in v) > 3]
    print(f"admissible primitive vectors: height <= 3 : {len(ADM3)}   "
          f"height <= {HMAX} : {len(ADMH)}   height in [4,{HMAX}] : {len(HIGH)}")

    # ------------------------------------------------------------------ rank 1
    print("\n--- rank-1 classes (M' of rank 1) ---")
    seen1, rows1 = set(), []
    for v in ADMH:
        k, _ = RL.lattice_key([list(v)])
        if k in seen1:
            continue
        seen1.add(k)
        ws = RL.witnesses([list(v)], PMAX=PMAX1, want=2)
        if not ws:
            continue
        n0 = tuple(k[0])
        lim = RL.rank1_limit(n0)
        h = max(abs(x) for x in n0)
        s3 = lim if h <= 3 else FLOOR
        rows1.append((lim - s3, lim, s3, h, n0, ws))
    rows1.sort(reverse=True)
    print(f"   realisable rank-1 classes of height <= {HMAX}: {len(rows1)}")
    print(f"   max o_inf over them: {max(r[1] for r in rows1)}")
    print(f"   MAX Delta = {rows1[0][0]} = {float(rows1[0][0]):.7f}"
          f"   (budget {float(BUDGET):.7f})")
    print(f"   count with Delta > 1/12: {sum(1 for r in rows1 if r[0] > BUDGET)}")
    for d, lim, s3, h, n0, ws in rows1[:6]:
        print(f"      n0 = {str(n0):>18} ht {h}  o_inf = {str(lim):>8}  "
              f"sub3 = {str(s3):>8}  Delta = {float(d):+.7f}  {ws[:1]}")

    # ------------------------------------------------------------------ rank 2
    print("\n--- rank-2 classes (M' of rank 2) ---")
    # arm A: planes containing at least one admissible height-<=3 vector
    keysA = {}
    for a in ADM3:
        for v in ADMH:
            p = plucker(a, v)
            if p is not None and p not in keysA:
                keysA[p] = (a, v)
    print(f"   arm A: distinct 2-planes containing an admissible height-<=3 vector:"
          f" {len(keysA)}")
    # arm B: planes spanned by two height-[4,HMAX] vectors and containing no
    # admissible height-<=3 vector
    keysB = {}
    for i in range(len(HIGH)):
        for j in range(i + 1, len(HIGH)):
            p = plucker(HIGH[i], HIGH[j])
            if p is None or p in keysA or p in keysB:
                continue
            keysB[p] = (HIGH[i], HIGH[j])
    print(f"   arm B: distinct 2-planes with NO admissible height-<=3 vector: "
          f"{len(keysB)}")

    out = []
    skipped = 0
    for arm, keys in (("A", keysA), ("B", keysB)):
        done = 0
        for p, (u, v) in keys.items():
            done += 1
            if done % 2000 == 0:
                print(f"   ... arm {arm}: {done}/{len(keys)}  kept {len(out)}  "
                      f"skipped {skipped}", flush=True)
            M = [list(u), list(v)]
            k, rk = RL.lattice_key(M)
            if rk != 2:
                continue
            # --- cheap first: the height-<=3 part.  rank 2 there forces Delta = 0.
            if arm == "B":
                s3, rk3 = FLOOR, 0
            else:
                sh = [a for a in ADM3 if in_plane(p, a)]
                if not sh:
                    s3, rk3 = FLOOR, 0
                else:
                    k3, rk3 = RL.lattice_key([list(a) for a in sh])
                    if rk3 == 2:
                        continue
                    s3 = limit_of_rows([list(r) for r in k3])
            rws = [list(r) for r in k]
            cc = cell_count(rws)
            if cc is None or cc > CELLCAP:
                skipped += 1
                continue
            lim = RL.rank2_limit(rws)
            out.append((lim - s3, lim, s3, rk3, arm, k, None))
    out.sort(key=lambda r: (-r[0], r[5]))
    # realisability is only needed for the classes near the top: check the top 400
    checked = []
    for rec in out[:400]:
        d, lim, s3, rk3, arm, k, _ = rec
        ws = RL.witnesses([list(r) for r in k], PMAX=PMAX, want=3)
        checked.append((d, lim, s3, rk3, arm, k, ws))
    out = checked
    print(f"\n   realisable rank-2 classes with sub3 of rank <= 1: {len(out)}"
          f"   (skipped for cell-count: {skipped})")
    if out:
        print(f"   max o_inf among them: {max(r[1] for r in out)}")
        print(f"   MAX Delta = {out[0][0]} = {float(out[0][0]):.7f}"
              f"   (budget {float(BUDGET):.7f})")
        nv = sum(1 for r in out if r[0] > BUDGET)
        print(f"   count with Delta > 1/12: {nv}")
        print(f"\n   {'Delta':>10} {'o_inf':>10} {'sub3':>10} rk3 arm  lattice"
              f"   witnesses (max speed)")
        for d, lim, s3, rk3, arm, k, ws in out[:30]:
            flag = "   <== REFUTES (H3u)" if d > BUDGET else ""
            print(f"   {float(d):>10.7f} {str(lim):>10} {str(s3):>10}  {rk3}  {arm}  "
                  f"{k}  {ws[:2]} maxsp {max(max(w) for w in ws)}{flag}")
