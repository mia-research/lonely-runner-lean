r"""
rt_limit_v1 -- EXACT rank-1 subtorus limits, in closed rational form.

Setting.  o(e) = |{theta : (a_rho XOR mu_rho) all distinct}|, a_rho = floor(4 frac(e_rho
theta)).  Write v_rho = frac(e_rho theta) in T^4.  The closure of the geodesic
{ (e_rho theta) : theta } is the subtorus  T_L = { v : n.v = 0 in R/Z for all n in L },
L = { n in Z^4 : n.e = 0 } -- for the LIMIT we replace L by its "low" part, the
sublattice generated by resonances of bounded height, and ask for the Haar average of
the good-indicator over that subtorus.  This module computes that average EXACTLY for
rank-1 lattices L = Z n0 with n0 primitive and having some entry n0_sigma = +-1.

Method (no equidistribution assumption is needed to state the value -- it is an exact
Haar integral over an explicit torus).  With n0_sigma = +-1, the coordinates
(v_rho)_{rho != sigma} are free and Haar-uniform on T^3, and

    4 v_sigma = SUM_{rho != sigma} c_rho (j_rho + s_rho),   c_rho = -n0_rho / n0_sigma,

writing v_rho = (j_rho + s_rho)/4 with j_rho in {0,1,2,3} uniform and s_rho in [0,1)
uniform, all independent.  Hence

    a_sigma = ( SUM c_rho j_rho + D ) mod 4,    D = floor( SUM_{rho != sigma} c_rho s_rho ),

and the law of D is an EXACT rational: after flipping the negative coordinates,
SUM c_rho s_rho = C_- + SUM b_rho u_rho with b_rho = |c_rho| > 0, and

    P( SUM b u < y ) = (1/(r! PROD b)) SUM_{J subset [r]} (-1)^{|J|} (y - SUM_{j in J} b_j)_+^r

(Lebesgue volume of a simplex-truncated box; exact in Fraction arithmetic).

So the limit is  (1/64) SUM_{j in {0..3}^3} SUM_d P(D=d) [nu all distinct]  -- a rational.

The r = 0 case (L = 0, no resonance) gives 24/256 = 3/32 by the same formula.
"""
from fractions import Fraction as F
from math import gcd
from functools import reduce
import itertools

MU = (0, 1, 2, 3)          # rho = 1,3,5,7
RHO = (1, 3, 5, 7)


# --------------------------------------------------- exact law of floor(sum b_j u_j)
def _cdf(bs, y):
    """P( sum b_j u_j < y ), u_j iid U[0,1), b_j > 0 integers.  Exact Fraction."""
    r = len(bs)
    if r == 0:
        return F(1) if y > 0 else F(0)
    tot = F(0)
    for k in range(r + 1):
        for J in itertools.combinations(range(r), k):
            t = F(y) - sum(bs[j] for j in J)
            if t > 0:
                tot += (-1) ** k * t ** r
    den = 1
    for i in range(2, r + 1):
        den *= i
    for b in bs:
        den *= b
    return tot / den


def law_of_D(cs):
    """cs = list of integers (may include 0).  Returns {d: P(floor(sum c_rho s_rho)=d)}."""
    bs = [abs(c) for c in cs if c != 0]
    shift = sum(c for c in cs if c < 0)          # sum c s = shift + sum b u
    if not bs:
        return {0: F(1)}
    lo, hi = shift, shift + sum(bs)
    out = {}
    for d in range(lo, hi + 1):
        p = _cdf(bs, d + 1 - shift) - _cdf(bs, d - shift)
        if p:
            out[d] = p
    assert sum(out.values()) == 1, (cs, out)
    return out


# ------------------------------------------------------------------ the limit
def rank1_limit(n0):
    """Exact Haar average of the good-indicator over { v in T^4 : n0.v = 0 }.
    Requires some |n0_sigma| = 1.  n0 must be primitive."""
    sig = next((i for i, x in enumerate(n0) if abs(x) == 1), None)
    if sig is None:
        raise ValueError("need an entry +-1")
    others = [i for i in range(4) if i != sig]
    cs = [F(-n0[i], n0[sig]) for i in others]
    assert all(c.denominator == 1 for c in cs)
    cs = [int(c) for c in cs]
    D = law_of_D(cs)
    tot = F(0)
    for js in itertools.product(range(4), repeat=3):
        base = sum(c * j for c, j in zip(cs, js))
        for d, p in D.items():
            a = [0, 0, 0, 0]
            for i, j in zip(others, js):
                a[i] = j
            a[sig] = (base + d) % 4
            if len({ar ^ mr for ar, mr in zip(a, MU)}) == 4:
                tot += p
    return tot / 64


def no_resonance_limit():
    tot = 0
    for a in itertools.product(range(4), repeat=4):
        if len({ar ^ mr for ar, mr in zip(a, MU)}) == 4:
            tot += 1
    return F(tot, 256)


# -------------------------------------------- admissible low-height resonances
def admissible(n):
    """n can be the resonance of SOME unit 4-tuple with positive speeds:
       (i) primitive, (ii) sum n_rho rho = 0 mod 8, (iii) mixed signs on the support."""
    if all(x == 0 for x in n):
        return False
    if reduce(gcd, [abs(x) for x in n]) != 1:
        return False
    if sum(x * r for x, r in zip(n, RHO)) % 8 != 0:
        return False
    sup = [x for x in n if x]
    if len(sup) < 2:
        return False
    if min(sup) > 0 or max(sup) < 0:
        return False
    return True


def witness(n, cap=400):
    """smallest primitive unit 4-tuple with n.e = 0 and speeds <= cap, or None."""
    idx = [i for i, x in enumerate(n) if x]
    free = [i for i in range(4) if i not in idx[:1]]
    best = None
    Q = cap // 8
    # brute force over three coordinates, solve the fourth
    j = idx[0]
    rest = [i for i in range(4) if i != j]
    for qs in itertools.product(range(Q + 1), repeat=3):
        e = [0, 0, 0, 0]
        for i, q in zip(rest, qs):
            e[i] = 8 * q + RHO[i]
        s = sum(n[i] * e[i] for i in rest)
        if s % n[j] != 0:
            continue
        ej = -s // n[j]
        if ej <= 0 or ej % 8 != RHO[j] % 8 or ej > cap:
            continue
        e[j] = ej
        if len(set(e)) != 4:
            continue
        if reduce(gcd, e) != 1:
            continue
        t = tuple(e)
        if best is None or max(t) < max(best):
            best = t
    return best


if __name__ == "__main__":
    import sys
    R = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    print("no low resonance:  o_inf =", no_resonance_limit(),
          "=", float(no_resonance_limit()))
    print()
    print(f"rank-1 subtorus limits for every admissible primitive n with ||n||_inf <= {R}")
    print("(only n with some entry +-1 -- the others need a 3-dim polytope volume)")
    print()
    print(f"{'n0':>22} {'entry+-1':>8} {'o_inf':>14} {'float':>10}  {'>1/3':>5}  witness tuple")
    seen = set()
    rows = []
    for n in itertools.product(range(-R, R + 1), repeat=4):
        if not admissible(n):
            continue
        neg = tuple(-x for x in n)
        if neg in seen:
            continue
        seen.add(n)
        if not any(abs(x) == 1 for x in n):
            rows.append((n, None, None))
            continue
        L = rank1_limit(n)
        rows.append((n, L, None))
    rows.sort(key=lambda r: (-(r[1] if r[1] is not None else F(-1))))
    nmax = F(0)
    over = []
    for n, L, _ in rows:
        if L is None:
            print(f"{str(n):>22} {'no':>8} {'(needs 3d vol)':>14}")
            continue
        w = witness(n, 400)
        flag = "YES" if L > F(1, 3) else ""
        if L > F(1, 3):
            over.append((n, L, w))
        nmax = max(nmax, L)
        print(f"{str(n):>22} {'yes':>8} {str(L):>14} {float(L):>10.6f}  {flag:>5}  {w}")
    print()
    print(f"largest rank-1 limit found: {nmax} = {float(nmax):.6f}   1/3 = {float(F(1,3)):.6f}")
    print(f"families whose LIMIT already exceeds 1/3: {len(over)}")
    for n, L, w in over:
        print(f"   n0 = {n}  o_inf = {L} = {float(L):.6f}  witness {w}")
