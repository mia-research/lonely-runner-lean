r"""
rt_tail_v2 -- EXHAUSTIVE measurement of the one inequality (H'') still needs.

The reduction (reports/n8_o_rate.md, Theorem 4 + Theorem 5) is:

   fix R.  For every primitive unit 4-tuple e,
     * either  rank L_R(e) = 3, and then max e_rho <= 3 sqrt(3) R^3   (finite; checked
       exhaustively by rt_finite_v1),
     * or  rank L_R(e) <= 2, and then  o(e) = o_inf(L_R^sat(e)) + Tail_R(e)  with
       o_inf <= 1/4 (rt_lattice_v1, exhaustive over classes of height <= R), so

              Tail_R(e) <= 1/12   for all such e     ==>   (H'').

This script measures Tail_R exactly on the whole box max e_rho <= SMAX, restricted to
the tuples with rank L_R <= 2 -- i.e. exactly the arm the open inequality quantifies over.
o, o_inf and Tail are exact Fractions.  Class limits are cached by saturated-lattice key.

usage:  python3 rt_tail_v2.py [R] [SMAX]
"""
import sys, itertools
from fractions import Fraction as F
from math import gcd, lcm
from functools import reduce

import rt_limit_v2 as RL
from ob_fast_v1 import o_fast

RHO = (1, 3, 5, 7)
THIRD = F(1, 3)
TWELFTH = F(1, 12)
R = int(sys.argv[1]) if len(sys.argv) > 1 else 2
SMAX = int(sys.argv[2]) if len(sys.argv) > 2 else 200

CACHE = {}


def guard(e):
    D = 4 * reduce(lcm, e)
    return max(4 * x for x in e) * D < 2 ** 63


def low_resonances(e, R):
    out = []
    for n3 in range(-R, R + 1):
        for n5 in range(-R, R + 1):
            for n7 in range(-R, R + 1):
                s = n3 * e[1] + n5 * e[2] + n7 * e[3]
                if s % e[0]:
                    continue
                n1 = -s // e[0]
                if abs(n1) > R or (n1 == n3 == n5 == n7 == 0):
                    continue
                out.append((n1, n3, n5, n7))
    return out


def class_limit(res):
    """exact Haar limit of the saturated lattice generated by `res` (rank <= 2)."""
    if not res:
        return F(24, 256), 0, ()
    M = [list(v) for v in res]
    B, rk = RL.kernel_basis(M)
    if rk == 0:
        return F(24, 256), 0, ()
    if rk >= 3:
        return None, rk, ()
    key, _ = RL.lattice_key(M)
    if key in CACHE:
        return CACHE[key][0], rk, key
    rows = [list(r) for r in key]
    val = RL.rank1_limit(tuple(rows[0])) if rk == 1 else RL.rank2_limit(rows)
    CACHE[key] = (val, rk)
    return val, rk, key


def gen(smax):
    Qs = [range((smax - r) // 8 + 1) for r in RHO]
    for qs in itertools.product(*Qs):
        e = tuple(8 * q + r for q, r in zip(qs, RHO))
        if len(set(e)) == 4 and reduce(gcd, e) == 1:
            yield e


if __name__ == "__main__":
    print(f"rt_tail_v2   R = {R}   SMAX = {SMAX}")
    print(f"Hadamard box at this R: 3*sqrt(3)*R^3 = {3*(3**0.5)*R**3:.1f}")
    print(f"Needed for (H''):  Tail_R <= 1/12 = {float(TWELFTH):.6f} "
          f"on every tuple with rank L_R <= 2\n")
    n = tot2 = 0
    worst = []
    limmax = F(0)
    bad = []
    for e in gen(SMAX):
        n += 1
        if not guard(e):
            continue
        res = low_resonances(e, R)
        lim, rk, key = class_limit(res)
        if lim is None:
            continue                      # rank 3 -> finite arm, handled by rt_finite_v1
        tot2 += 1
        o = o_fast(e)
        tail = o - lim
        limmax = max(limmax, lim)
        worst.append((tail, o, lim, rk, e))
        if tail > TWELFTH:
            bad.append((tail, o, lim, rk, e))
        if n % 100000 == 0:
            print(f"   ... {n} scanned, {tot2} in the rank<=2 arm", flush=True)
    # the sharp form: (H'') on this arm is exactly  Tail_R <= 1/3 - o_inf(class).
    ratio = sorted(((F(t, 1) / (THIRD - lim) if THIRD > lim else None), t, o, lim, rk, e)
                   for t, o, lim, rk, e in worst)
    ratio = [r for r in ratio if r[0] is not None]
    ratio.sort(key=lambda r: -r[0])
    worst.sort(reverse=True)
    print(f"\n  primitive unit tuples scanned:            {n}")
    print(f"  with rank L_{R} <= 2 (the open arm):        {tot2}")
    print(f"  with rank L_{R} = 3 (finite arm):           {n - tot2}")
    print(f"  distinct classes met:                     {len(CACHE)}")
    print(f"  max class limit o_inf met:                {limmax} = {float(limmax):.6f}")
    print(f"\n  MAX Tail_{R} over the open arm: {worst[0][0]} = {float(worst[0][0]):.8f}"
          f"   (need <= 1/12 = {float(TWELFTH):.8f})")
    print(f"  tuples violating Tail_{R} <= 1/12: {len(bad)}")
    print(f"\n  top 20 by Tail_{R}:")
    print(f"     {'e':>22} {'rk':>3} {'o':>11} {'o_inf':>11} {'Tail':>11} "
          f"{'o_inf+1/12':>11}")
    for tail, o, lim, rk, e in worst[:20]:
        print(f"     {str(e):>22} {rk:>3} {float(o):>11.7f} {float(lim):>11.7f} "
              f"{float(tail):>11.7f} {float(lim + TWELFTH):>11.7f}"
              f"{'   VIOLATES' if tail > TWELFTH else ''}")
    print(f"\n  THE SHARP FORM.  On this arm (H'') is exactly "
          f"Tail_{R} <= 1/3 - o_inf(class).")
    print(f"  Report the ratio  Tail_{R} / (1/3 - o_inf);  (H'') on the arm <=> ratio <= 1.")
    print(f"     {'e':>22} {'rk':>3} {'o_inf':>9} {'Tail':>10} {'margin':>9} {'ratio':>8}")
    for rr, t, o, lim, rk, e in ratio[:20]:
        print(f"     {str(e):>22} {rk:>3} {float(lim):>9.6f} {float(t):>10.6f} "
              f"{float(THIRD-lim):>9.6f} {float(rr):>8.4f}"
              f"{'   RATIO > 1' if rr > 1 else ''}")
    print(f"  max ratio over the arm: {float(ratio[0][0]):.4f}  "
          f"(count above 1: {sum(1 for r in ratio if r[0] > 1)})")
    # per class-limit table
    byl = {}
    for t, o, lim, rk, e in worst:
        d = byl.setdefault(lim, [F(0), None, 0])
        d[2] += 1
        if t > d[0]:
            d[0], d[1] = t, e
    print(f"\n  max Tail_{R} by class limit (top 12 classes by limit):")
    print(f"     {'o_inf':>10} {'n':>8} {'maxTail':>10} {'margin':>9} {'ratio':>8}  argmax")
    for lim in sorted(byl, reverse=True)[:12]:
        mt, arg, cnt = byl[lim]
        marg = THIRD - lim
        print(f"     {str(lim):>10} {cnt:>8} {float(mt):>10.6f} {float(marg):>9.6f} "
              f"{float(mt/marg):>8.4f}  {arg}")

    if bad:
        print(f"\n  ALL VIOLATIONS of Tail_{R} <= 1/12 "
              f"(these do NOT refute (H''); they break the clean reduction):")
        bad.sort(reverse=True)
        for tail, o, lim, rk, e in bad[:40]:
            print(f"     {str(e):>22} rk {rk}  o = {o} = {float(o):.7f}  "
                  f"o_inf = {lim}  Tail = {float(tail):.7f}"
                  f"{'   AND o > 1/3' if o > THIRD else ''}")
        print(f"  of the {len(bad)} violations, "
              f"{sum(1 for t,o,l,r,e in bad if o > THIRD)} also have o > 1/3, and "
              f"{sum(1 for t,o,l,r,e in bad if o > THIRD and e not in {(1,3,5,7),(1,11,5,7)})}"
              f" of those are outside the known exception list")
