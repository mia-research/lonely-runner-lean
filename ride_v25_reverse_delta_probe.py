def canonical_arrangement(counts: list[int]) -> list[int]:
    """
    Build the K-canonical arrangement: digits sorted descending.
    This is what desc(n) looks like — the starting form before desc - asc.
    """
    digits = []
    for d in range(9, -1, -1):
        digits.extend([d] * counts[d])
    return digits


def file_natural_order(raw: bytes) -> list[int]:
    """
    The file's natural digit sequence (lossless decimal representation).
    """
    decimal = binary_to_decimal_lossless(raw)
    return list(str_to_digits(decimal))


def apply_reverse_delta(
    k_canonical: list[int],
    k_counts: list[int],
    target_counts: list[int],
) -> list[int]:
    """
    Starting from the K-canonical arrangement, swap out surplus digits for
    deficit digits (ascending deficit order, left-to-right scan) to reach
    the target multiset.

    This is the reverse analogue of deterministic_frequency_patch but applied
    to the sorted canonical form rather than the K-source fixed-point.
    """
    delta = [target_counts[d] - k_counts[d] for d in range(10)]
    deficits: list[int] = []
    for d in range(10):
        if delta[d] > 0:
            deficits.extend([d] * delta[d])

    surplus_remaining = [max(0, -v) for v in delta]
    patched = list(k_canonical)
    deficit_idx = 0

    for pos, digit in enumerate(k_canonical):
        if surplus_remaining[digit] <= 0:
            continue
        patched[pos] = deficits[deficit_idx]
        surplus_remaining[digit] -= 1
        deficit_idx += 1

    if deficit_idx != len(deficits):
        raise ValueError("reverse delta did not consume all deficits")

    return patched


def measure_reverse_direction(raw: bytes) -> dict:
    t0 = time.perf_counter()

    # --- Target info ---
    decimal = binary_to_decimal_lossless(raw)
    target_counts = digit_counts(decimal)
    target_digits = list(str_to_digits(decimal))
    n_digits = len(target_digits)

    # --- Nearest K multiset (thermodynamic projection) ---
    v0, a, b, v9, freq_l1 = nearest_thermo_params(target_counts)
    k_counts = thermo_counts_from_params(v0, a, b, v9)

    # --- Build K-canonical arrangement (desc sorted) ---
    k_canonical = canonical_arrangement(k_counts)

    # --- Apply reverse delta to match target multiset ---
    try:
        patched_canonical = apply_reverse_delta(k_canonical, k_counts, target_counts)
    except ValueError as e:
        return {"error": str(e)}

    # Verify multiset match
    from collections import Counter
    if Counter(patched_canonical) != Counter(target_digits):
        return {"error": "multiset mismatch after reverse delta"}

    prep_time = time.perf_counter() - t0

    # --- Measure order mile: patched_canonical -> target ---
    t1 = time.perf_counter()
    perm_rev = list(build_perm_target_to_source(
        bytearray(target_digits),
        bytearray(patched_canonical),
    ))
    mile_rev, cycles_rev = permutation_cycle_mile(perm_rev)
    plan_rev = build_rsn_cycle_plan(perm_rev)
    order_time = time.perf_counter() - t1

    # --- Measure forward direction mile for comparison (v18 style) ---
    t2 = time.perf_counter()
    try:
        source_fwd, target_fwd, params_fwd, l1_fwd = materialise_source_and_target(raw)
        perm_fwd = list(build_perm_target_to_source(
            bytearray(target_fwd),
            bytearray(source_fwd),
        ))
        mile_fwd, cycles_fwd = permutation_cycle_mile(perm_fwd)
        plan_fwd = build_rsn_cycle_plan(perm_fwd)
    except Exception as e:
        mile_fwd = -1
        cycles_fwd = -1
        plan_fwd = {"non_trivial": -1}
        l1_fwd = -1
    fwd_time = time.perf_counter() - t2

    delta_l1 = sum(abs(target_counts[d] - k_counts[d]) for d in range(10))

    return {
        "file_bytes": len(raw),
        "n_digits": n_digits,
        "freq_l1_to_k": delta_l1,
        # Reverse direction (new)
        "reverse_mile": mile_rev,
        "reverse_cycles": cycles_rev,
        "reverse_non_trivial": plan_rev["non_trivial"],
        # Forward direction (v18 baseline)
        "forward_mile": mile_fwd,
        "forward_cycles": cycles_fwd,
        "forward_non_trivial": plan_fwd["non_trivial"],
        # Winner
        "reverse_wins_on_mile": mile_rev < mile_fwd if mile_fwd >= 0 else None,
        "mile_ratio_rev_over_fwd": mile_rev / mile_fwd if mile_fwd > 0 else None,
        "cycle_ratio_rev_over_fwd": plan_rev["non_trivial"] / plan_fwd["non_trivial"]
            if plan_fwd["non_trivial"] > 0 else None,
        "prep_time": round(prep_time, 3),
        "order_time": round(order_time, 3),
        "fwd_time": round(fwd_time, 3),
    }


def run(path: Path) -> None:
    raw = path.read_bytes()
    print(f"\n{'=' * 72}")
    print(f"  RIDE V25 — Reverse-delta probe: {path.name}")
    print(f"{'=' * 72}")
    print(f"  Raw bytes: {len(raw):,}")

    result = measure_reverse_direction(raw)

    if "error" in result:
        print(f"  ERROR: {result['error']}")
        return

    print(f"  Digits: {result['n_digits']:,}")
    print(f"  Freq L1 to nearest K multiset: {result['freq_l1_to_k']:,}")
    print()
    print(f"  REVERSE direction (K-canonical -> target):")
    print(f"    Mile:        {result['reverse_mile']:,}")
    print(f"    Cycles:      {result['reverse_cycles']:,}")
    print(f"    Non-trivial: {result['reverse_non_trivial']:,}")
    print()
    print(f"  FORWARD direction (K-source-patched -> target, v18 baseline):")
    print(f"    Mile:        {result['forward_mile']:,}")
    print(f"    Cycles:      {result['forward_cycles']:,}")
    print(f"    Non-trivial: {result['forward_non_trivial']:,}")
    print()
    if result["mile_ratio_rev_over_fwd"] is not None:
        pct = result["mile_ratio_rev_over_fwd"] * 100
        winner = "REVERSE" if result["reverse_wins_on_mile"] else "FORWARD"
        print(f"  Winner on mile: {winner}  (reverse/forward ratio = {pct:.1f}%)")
        print(f"  Cycle ratio (rev/fwd): {result['cycle_ratio_rev_over_fwd']:.2f}")
    print(f"  Prep time: {result['prep_time']}s  Order time: {result['order_time']}s")


