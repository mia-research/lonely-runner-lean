"""E264 (2026-10-02): which cluster flanks are free across c's band run, on every E118-construction member (seed 118's 547 from
residual_members_C_list_v1.json, plus seeds 201..210 regenerated by restricted_b_v1.part1_seed's construction).
Per member: the state (free / alone / handoff) of each cluster flank by rank (1 = slowest of the six); the free ranks.
Reports: members with no free flank; members whose slowest flank (rank 1) is not free; the distribution of the least free rank;
whether the cascade's landing flank (earliest first-clear opening) is the rank-1 flank."""
import sys, os, json, io, contextlib
from collections import Counter
from multiprocessing import Pool
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE); sys.path.insert(0, '../band_cert_v1'); sys.path.insert(0, HERE)
import restricted_b_v1 as R
from hole_C1_flanks_v1 import flank

def members(seed):
    src = open(R.NN + '/residual_members_C_v1.py').read().split("# through the cascade")[0].replace('random.Random(118)', 'random.Random(%d)' % seed)
    ns = {}
    with R.in_nn(), contextlib.redirect_stdout(io.StringIO()):
        exec(src, ns)
    return [(seed, m, tuple(sorted(S))) for m in 'AB' for S in ns['found'][m]]

def read(item):
    seed, mode, S = item
    c = S[0]; cl = list(S[1:])
    st = [flank(c, cl, e)['state'] for e in cl]
    return seed, mode, st

if __name__ == '__main__':
    M = json.load(open(R.NN + '/residual_members_C_list_v1.json'))
    items = [(118, m, tuple(S)) for m in 'AB' for S in M[m]]
    with Pool(10) as pool:
        for part in pool.map(members, range(201, 211)): items += part
        res = pool.map(read, items, chunksize=40)
    out = open('free_ranks_v1.out', 'w'); out.write(__doc__ + "\n")
    def w(s): out.write(s + "\n"); out.flush()
    w("members read: %d (seed 118: %d)" % (len(res), sum(1 for r in res if r[0] == 118)))
    for mode in 'AB':
        X = [r for r in res if r[1] == mode]
        nofree = sum(1 for _, _, st in X if 'free' not in st)
        r1 = Counter(st[0] for _, _, st in X)
        least = Counter(next(i + 1 for i, s in enumerate(st) if s == 'free') for _, _, st in X if 'free' in st)
        top = Counter(st[-1] for _, _, st in X)
        w("mode %s (%d): no free cluster flank: %d; rank-1 (slowest) flank state: %s; least free rank: %s; fastest flank state: %s" % (
            mode, len(X), nofree, dict(r1), dict(sorted(least.items())), dict(top)))
        w("   number of free flanks per member: %s" % dict(sorted(Counter(sum(1 for s in st if s == 'free') for _, _, st in X).items())))
    out.close(); print(open('free_ranks_v1.out').read()[len(__doc__):])
