#!/usr/bin/env python3
"""Observation/check, gcd(v1, D) = g > 1, non-uniform §6 sets, built at random (D' = D/g, c, v1 = g a with gcd(a, D') = 1,
v4 in the near-runner range, v5 > v4).
C (g not | v4): delta = v4 - v3 is not a multiple of g, so at the k = k0 + D' i (i < g) with one fixed runner-1 phase j/D'
in [1/6, 5/9], runner 4's phases k delta / D form a coset of the subgroup generated by delta/g (mod 1), of order
h = g / gcd(delta, g) >= 2: consecutive points 1/h <= 1/2 apart. Check: (i) the arc A has length >= 1/2 (the near-runner
case); (ii) the coset meets A, i.e. the after-window region closes with one runner-1 phase -- and report h.
B (g | v4): the meeting-window data are those of the reduced (v1..v4)/g, v5/g (rational) at D' with gcd(a, D') = 1:
check that the reduced instance is closed by the D >= 15 branch's classification when D' >= 15 (uniform / generic
|lam'| >= 2 / sum lemma / diagonal region), and that the original and reduced region tests agree."""
import math, random, sys
from fractions import Fraction as F
from collections import Counter
from s6_rest_v1 import uniform, arcs, on_arc, region_ks, sum_ok, meet_fold
def branch_classify(S):
    v1, v2, v3, v4, v5 = S; D = v3 - v2
    if 4 * v2 * v3 <= v4 * (5 * v2 - v3): return "uniform"
    lam = (v4 * pow(v1, -1, D)) % D; lam = lam - D if lam > D // 2 else lam
    if abs(lam) >= 2: return "generic"
    if region_ks(S, range(D)) is not None: return f"diagonal lam {lam}"
    if sum_ok(S): return "sum"
    return f"REST lam {lam}"
random.seed(int(sys.argv[1]) if len(sys.argv) > 1 else 3)
cC = Counter(); hC = Counter(); cB = Counter(); agree = Counter(); exs = []
tries = 0
while sum(cC.values()) + sum(cB.values()) < 20000 and tries < 10**6:
    tries += 1
    g = random.choice([2, 2, 2, 3, 3, 4, 5, 6, 7, 8, 9, 10, 12, 15, 30])
    Dp = random.choice(list(range(2, 15)) + list(range(15, 80)))
    c = random.choice([1, 1, 2, 2, 3, 4, 5, 7, 10, 20, 50]); D = g * Dp
    v2, v3 = c * D, (c + 1) * D
    a = random.randrange(1, max(2, (v3 - 1) // (3 * g) + 1))
    if math.gcd(a, Dp) != 1 or 3 * g * a >= v3 or a % Dp == 0 and Dp == 1: continue
    v1 = g * a
    if v1 >= v2: continue
    # near-runner: v4 < 4 v2 v3 / (5 v2 - v3)
    top = (4 * v2 * v3) // (5 * v2 - v3)
    if top <= v3 + 1: continue
    v4 = random.randrange(v3 + 1, top + 1); v5 = v4 + random.choice([1, 1, 2, 3, random.randrange(1, 5 * v4)])
    S = (v1, v2, v3, v4, v5)
    if uniform(S): continue
    d = v4 - v3
    if v4 % g:
        A, _ = arcs(S); L = A[1] - A[0]
        cC["arc >= 1/2" if L >= F(1, 2) else "ARC < 1/2"] += 1
        inv = pow(a, -1, Dp); j = next(j for j in range(Dp) if F(1, 6) <= F(j, Dp) <= F(5, 9))
        ks = [(j * inv) % Dp + Dp * i for i in range(g)]
        hC[g // math.gcd(d, g)] += 1
        ok = region_ks(S, ks) is not None
        cC["one phase closes" if ok else "ONE PHASE FAILS"] += 1
        if not ok and len(exs) < 6: exs.append(S)
    else:
        R = (a, v2 // g, v3 // g, v4 // g, F(v5, g))
        if Dp >= 15:
            cB["D'>=15: " + branch_classify(R).split(" lam")[0] if not branch_classify(R).startswith("REST") else "D'>=15: REST"] += 1
        else:
            cB["D'<15"] += 1
        o, r = region_ks(S, range(D)) is not None, region_ks(R, range(Dp)) is not None
        agree["region same on S and reduced" if o == r else "DIFFER"] += 1
print("C (g not | v4):", dict(cC), "  h = order of runner 4's coset:", dict(sorted(hC.items())), " failures", exs)
print("B (g | v4):", dict(cB), dict(agree))
