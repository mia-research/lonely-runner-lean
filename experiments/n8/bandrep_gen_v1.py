#!/usr/bin/env python3
"""bandrep_gen_v1.py -- band box-certificate replay GENERATOR (Track B bulk replay).

Reads the on-disk per-box certificate records and emits Lean 4 replay files
(Fresh/BandReplay*.lean) consuming the banked schema templates:

  mode pinch     tail_h3_pinch_dump_v1.jsonl (E843, 509 h3-straddler boxes, D=512)
                 -> per-box BandPinch instances (schema class 4), cloning the worked
                    bandPinch_kBox1 pattern of Fresh/BandPinchData.lean.
  mode hullcheck frontier_type_dump_v1.json (E847, 33 (range, window-type) records)
                 -> tests whether each type's interval hull is certificate-bearing
                    (the five SideWindowCertV hv families at the hull's extreme corner).
                    Quantifies the E846 phenomenon for the [29,41) census: hulls are
                    descriptive, not certificates.  No Lean output.

New-file discipline: emits only Fresh/BandReplay*.lean; edits nothing existing.
All arithmetic exact (Fractions / integers).
"""
import json, sys, os
from fractions import Fraction

N8 = os.path.dirname(os.path.abspath(__file__))
FRESH = os.path.join(os.path.dirname(N8), "LonelyRunnerFresh", "Fresh")

# ---------------------------------------------------------------- pinch mode

# Per-window per-reading envelopes from Fresh/BandPinchData.lean (Lean indices
# 1,2,3,5 = rho2,rho3,rho4,rho6); rho5 cell = W, rho7 cell unconstrained.
PINCH_WINDOWS = {
    2645: {1: (953, 1586), 2: (953, 1586), 3: (1800, 2432), 5: (3493, 4125)},
    2646: {1: (953, 1586), 2: (953, 1586), 3: (1800, 2433), 5: (3495, 4126)},
    2647: {1: (954, 1587), 2: (954, 1587), 3: (1801, 2434), 5: (3496, 4128)},
    2686: {1: (968, 1610), 2: (968, 1610), 3: (1828, 2470), 5: (3547, 4189)},
    2687: {1: (968, 1611), 2: (968, 1611), 3: (1828, 2471), 5: (3549, 4190)},
    2726: {1: (982, 1634), 2: (982, 1634), 3: (1855, 2506), 5: (3600, 4251)},
    2727: {1: (983, 1635), 2: (983, 1635), 3: (1856, 2507), 5: (3601, 4253)},
}
SHARED_M = {0: 1, 1: 1, 2: 2, 4: 4}

def pinch_records():
    recs = []
    with open(os.path.join(N8, "tail_h3_pinch_dump_v1.jsonl")) as f:
        for ln, line in enumerate(f):
            d = json.loads(line)
            k6 = d["k6"]           # artifact indices 0..5 = rho2..rho7
            W = d["lo5P"]
            ok, why = True, []
            if d["D"] != 512: ok, _ = False, "D!=512"
            if d["lo5P"] != d["hi5P"]: ok, why = False, why + ["lo5P!=hi5P"]
            if k6[3] != W: ok, why = False, why + ["rho5 cell != W"]
            if {int(k): v for k, v in d["m"].items()} != SHARED_M:
                ok, why = False, why + ["m differs from shared tuple"]
            env = PINCH_WINDOWS.get(W)
            if env is None: ok, why = False, why + ["W not a banked window"]
            else:
                for li, (lo, hi) in env.items():
                    if not (lo <= k6[li - 1] <= hi):
                        ok, why = False, why + [f"rho{li+1} cell {k6[li-1]} outside window envelope"]
            recs.append({"line": ln, "k6": k6, "W": W, "ok": ok, "why": why})
    return recs

def emit_pinch(out_path, recs, first, count):
    """Emit `count` boxes starting at record index `first` (0-based over the JSONL)."""
    chosen = [r for r in recs[first:first + count]]
    L = []
    A = L.append
    A("import Fresh.BandPinchData")
    A("")
    A("/-!")
    A(f"# Band replay, pinch family tranche: JSONL lines {chosen[0]['line']+1}-"
      f"{chosen[-1]['line']+1} of 509 (E843)")
    A("")
    A("Generated by `experiments/n8/bandrep_gen_v1.py` (mode pinch) from")
    A("`experiments/n8/tail_h3_pinch_dump_v1.jsonl` (exact, D = 512).  Per-box")
    A("instantiations of the worked `bandPinch_kBox1` pattern of")
    A("`Fresh.BandPinchData`: each box's k6 tuple adjoins the artifact-silent")
    A("rho1 cell `k 0 = 511`, its window is one of the seven banked")
    A("`pinchWindow_<W>` theorems (cell-vs-envelope checked at generation time),")
    A("and the glue `bandPinch_of_window_cell` gives schema class 4 (`BandPinch`),")
    A("hence `Fresh.BandNoCarve.noCarve_of_pinch` excludes carving `[1,7]` on the")
    A("box's plane.  Data-side checks at generation time (all exact): the record's")
    A("m-tuple is the shared tuple, `lo5P = hi5P = k6[3]`, and each cell lies in")
    A("its window's envelope.  Nothing existing is edited.")
    A("-/")
    A("")
    ns = "Fresh." + os.path.splitext(os.path.basename(out_path))[0]
    A(f"namespace {ns}")
    A("")
    A("open Fresh.BandPinchData")
    A("")
    for r in chosen:
        n = r["line"] + 1
        k = r["k6"]; W = r["W"]
        kv = [511, k[0], k[1], k[2], W, k[4], k[5]]
        A(f"/-- Box {n} of the dump (window W = {W}): k = ![{', '.join(map(str, kv))}] "
          f"(rho7 cell {k[5]}, unconstrained by `PinchIntCond`). -/")
        A(f"def kBox{n} : Fin 7 → ℤ := ![{', '.join(map(str, kv))}]")
        A("")
        A(f"theorem pinchIntCond_kBox{n} :")
        A(f"    Fresh.Pinch.PinchIntCond 11 3 (512 : ℤ) kBox{n} mjShared {W} {W} :=")
        A(f"  pinchWindow_{W} (by simp [mjShared]) (by simp [mjShared]) (by simp [mjShared])")
        A(f"    (by simp [mjShared]) (by simp [mjShared]) (by simp [kBox{n}]) (by simp [kBox{n}])")
        A(f"    (by simp [kBox{n}]) (by simp [kBox{n}]) (by simp [kBox{n}])")
        A("")
        A(f"/-- Box {n} consumption: every arrangement in the box on the h3 tangency")
        A(f"plane is a `BandPinch` tuple (schema class 4). -/")
        A(f"theorem bandPinch_kBox{n} {{g : Fin 7 → ℝ}}")
        A(f"    (hbox : Fresh.Pinch.InBox 512 kBox{n} g)")
        A(f"    (hplane : Fresh.Pinch.TangentPlane 11 3 g) :")
        A(f"    Fresh.BandNoCarve.BandPinch g :=")
        A(f"  bandPinch_of_window_cell pinchIntCond_kBox{n} hbox rfl hplane")
        A("")
    # totality over the tranche: per-window groups, then a 7-case top disjunction
    names = [f"kBox{r['line']+1}" for r in chosen]
    wmap = {r["line"] + 1: r["W"] for r in chosen}
    groups = {}
    for nm in names:
        groups.setdefault(wmap[int(nm[4:])], []).append(nm)
    A("/-! ### The tranche's per-box totality (per window, then the 7-case union) -/")
    A("")
    def block(idx, names_l, var, ind):
        if idx == len(names_l) - 1:
            return [f"{ind}exact bandPinch_{names_l[idx]} {var} hplane"]
        out = [f"{ind}rcases {var} with hb | {var}",
               f"{ind}· exact bandPinch_{names_l[idx]} hb hplane",
               f"{ind}·"]
        return out + block(idx + 1, names_l, var, ind + "  ")
    gnames = []
    for W in sorted(groups):
        gl = groups[W]
        gn = f"bandPinch_win{W}"
        gnames.append(gn)
        disj = f"Fresh.Pinch.InBox 512 {gl[-1]} g"
        for nm in reversed(gl[:-1]):
            disj = f"(Fresh.Pinch.InBox 512 {nm} g ∨ {disj})"
        A(f"set_option maxRecDepth 800000 in")
        A(f"/-- Window {W}'s {len(gl)} boxes of the tranche cover their union's plane. -/")
        A(f"theorem {gn} {{g : Fin 7 → ℝ}}")
        A(f"    (hbox : {disj})")
        A("    (hplane : Fresh.Pinch.TangentPlane 11 3 g) :")
        A("    Fresh.BandNoCarve.BandPinch g := by")
        L.extend(block(0, gl, "hbox", "  "))
        A("")
    A("set_option maxRecDepth 800000 in")
    A("/-- The tranche's whole box union (all seven windows) on the plane. -/")
    A("theorem bandPinch_tranche_discharged {g : Fin 7 → ℝ}")
    wlist = sorted(groups.items())
    alldisj = None
    for W, gl in reversed(wlist):
        gdisj = f"Fresh.Pinch.InBox 512 {gl[-1]} g"
        for nm in reversed(gl[:-1]):
            gdisj = f"(Fresh.Pinch.InBox 512 {nm} g ∨ {gdisj})"
        alldisj = gdisj if alldisj is None else f"({gdisj} ∨ {alldisj})"
    A(f"    (hbox : {alldisj})")
    A("    (hplane : Fresh.Pinch.TangentPlane 11 3 g) :")
    A("    Fresh.BandNoCarve.BandPinch g := by")
    def topblock(idx, var, ind):
        if idx == len(gnames) - 1:
            return [f"{ind}exact {gnames[idx]} {var} hplane"]
        out = [f"{ind}rcases {var} with hb | {var}",
               f"{ind}· exact {gnames[idx]} hb hplane",
               f"{ind}·"]
        return out + topblock(idx + 1, var, ind + "  ")
    L.extend(topblock(0, "hbox", "  "))
    A("")
    for nm in names:
        A(f"#print axioms bandPinch_{nm}")
    A("#print axioms bandPinch_tranche_discharged")
    A("")
    A(f"end {ns}")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    return len(chosen)

# ------------------------------------------------------------ hullcheck mode

def hullcheck():
    """For each (range, window-type) record of E847's dump, test whether the type's
    five SideWindowCertV families hold at the hull's extreme corner (exact)."""
    d = json.load(open(os.path.join(N8, "frontier_type_dump_v1.json")))
    print(f"{'range':8s} {'X':>12s} {'Y':>12s} {'laps':24s} {'boxes':>7s}  verdict")
    npass = nfail = 0
    failnames = []
    for e in d:
        hull = e["hull"]
        lo = {k: Fraction(v[0]) for k, v in hull.items()}
        hi = {k: Fraction(v[1]) for k, v in hull.items()}
        laps = e["laps"]            # (8j+1) values over rho2..rho7
        j = [(v - 1) // 8 for v in laps]
        # X = na/rho_ka: ka = reading whose lap value equals na = laps value at ka
        # Y = nb/rho_kb: nb = (8j_kb+7), kb = reading whose (8j+7) equals nb
        keys = ["rho2", "rho3", "rho4", "rho5", "rho6", "rho7"]
        # parse X, Y descriptors for cross-check
        xa, ya = e["X"], e["Y"]
        na = int(xa.split("/")[0]); nb = int(ya.split("/")[0])
        ka = keys.index(xa.split("/")[1])       # 0-based over rho2..rho7
        kb = keys.index(ya.split("/")[1])
        # hv families at hull corners (Lean indices: i=0 pinned rho1=1)
        bad = []
        if hi[keys[ka]] > na: bad.append("hv1")
        if na * hi[keys[kb]] > nb * lo[keys[ka]]: bad.append("hv2")
        if nb > 7 * lo[keys[kb]]: bad.append("hv3")
        for idx, key in enumerate(keys):
            l1 = 8 * j[idx] + 1
            if idx == ka: continue
            if l1 * hi[keys[ka]] > na * lo[key]: bad.append(f"hv4:{key}")
            l2 = 8 * j[idx] + 7
            if idx == kb: continue
            if nb * hi[key] > l2 * lo[keys[kb]]: bad.append(f"hv5:{key}")
        if bad:
            nfail += 1; failnames.append((e["range_rho7"], xa, ya, bad))
            print(f"{e['range_rho7']:8s} {xa:>12s} {ya:>12s} {str(laps):24s} {e['boxes']:7d}  FAIL {bad}")
        else:
            npass += 1
            print(f"{e['range_rho7']:8s} {xa:>12s} {ya:>12s} {str(laps):24s} {e['boxes']:7d}  PASS")
    print(f"\nhull certificate-bearing: {npass}/33 pass, {nfail}/33 fail")
    for f_ in failnames:
        print("  FAIL:", f_)


# --------------------------------------------------------------- r0 mode

BASE = 1 << 20

def _feasible_R0(k, D):
    """Exact feasible R0 set for a 6-tuple of cells (k, depth D): intersection over
    readings of the unions of per-lap intervals [(8j+1)D/k_i, (8j+7)D/(k_i+1)]."""
    def union(ki):
        out = []
        for j in range(0, (8 * ki + 7) // 8 + 2):
            lo = Fraction((8 * j + 1) * D, ki)
            hi = Fraction((8 * j + 7) * D, ki + 1)
            if lo <= hi:
                out.append((lo, hi))
        return out
    sets = [union(ki) for ki in k]
    # intersect unions of intervals by sweeping candidate left endpoints
    best = None
    for lo0, hi0 in sets[0]:
        cur_lo, cur_hi = lo0, hi0
        ok = True
        for other in sets[1:]:
            # overlap of [cur_lo, cur_hi] with the union `other`
            frag = None
            for lo, hi in other:
                a, b = max(cur_lo, lo), min(cur_hi, hi)
                if a <= b and (frag is None or a < frag[0]):
                    frag = (a, b)
            if frag is None:
                ok = False
                break
            cur_lo, cur_hi = frag
        if ok and (best is None or cur_lo < best[0]):
            best = (cur_lo, cur_hi)
    return best

def r0_recertify(limit_bands=None, verbose=True):
    """Re-run the E832 D=1 fixed-R0 certifier over all [25,29) root boxes with
    per-box recording; validate against the ledger count (541,537 certified)."""
    import itertools
    certified = 0
    roots = 0
    recs = []
    for k7 in range(25, 29):
        for tail in itertools.combinations_with_replacement(range(1, k7 + 1), 5):
            k = tuple(tail) + (k7,)
            roots += 1
            iv = _feasible_R0(k, 1)
            if iv is None:
                continue
            lo, hi = iv
            r = -((-lo.numerator * BASE) // lo.denominator)  # ceil(lo * BASE)
            if r * BASE > hi.numerator * BASE // hi.denominator * BASE:  # r/BASE > hi?
                if Fraction(r, BASE) > hi:
                    continue
            # integer verification: FixedClearIntCond D=1 base=BASE
            ok_j = []
            good = True
            for ki in k:
                found = None
                for j in range(0, (8 * ki + 7) // 8 + 2):
                    if (8 * j + 1) * BASE <= r * ki and r * (ki + 1) <= (8 * j + 7) * BASE:
                        found = j
                        break
                if found is None:
                    good = False
                    break
                ok_j.append(found)
            if good:
                certified += 1
                if len(recs) < 400000:
                    recs.append({"k": k, "r": r, "j": ok_j})
    if verbose:
        print(f"roots={roots} certified at D=1 (re-dump)={certified} (ledger: 541537)")
    return recs, roots, certified

# ------------------------------------------------------------------- main

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "hullcheck"
    if mode == "hullcheck":
        hullcheck()
    elif mode == "r0":
        r0_recertify()
    elif mode == "pinch":
        recs = pinch_records()
        nbad = sum(1 for r in recs if not r["ok"])
        print(f"records: {len(recs)}, window/envelope violations: {nbad}")
        for r in recs:
            if not r["ok"]:
                print("  line", r["line"] + 1, r["why"])
        first = int(sys.argv[2]) if len(sys.argv) > 2 else 1   # skip line 1 (banked kBox1)
        count = int(sys.argv[3]) if len(sys.argv) > 3 else len(recs)
        out = sys.argv[4] if len(sys.argv) > 4 else os.path.join(FRESH, "BandReplayPinchT1.lean")
        chosen = [r for r in recs[first:first + count]]
        assert all(r["ok"] for r in chosen), "chosen records must pass checks"
        n = emit_pinch(out, recs, first, count)
        print(f"emitted {n} boxes -> {out}")
    else:
        sys.exit("unknown mode")

if __name__ == "__main__":
    main()
