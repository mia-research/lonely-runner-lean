"""m4_zone_lean_gen_v4 -- M4 zone certificates: one file per chunk, kernel theorem per block.

v3 (one decide +kernel per chunk) reached 28 GB on C_4_5_6 (364 tuples, 36,770 nodes): the
kernel cache holds every intermediate zone matrix of the declaration.  v4 splits each chunk into
blocks of at most BUDGET certificate nodes:
  def b_v_w_x_k : List (List N x List N) := [(tail, code), ...]
  theorem zb_v_w_x_k : zblk v w x b_v_w_x_k = true := by decide +kernel
  def L_v_w_x := b_.._0 ++ b_.._1 ++ ...;  def cs_v_w_x := L_v_w_x.map (fun p => ZT.dec1 p.2)
  theorem hg_v_w_x : gen 3 x = L_v_w_x.map Prod.fst := by decide +kernel
  theorem z_v_w_x : zchunk v w x cs_v_w_x = true  (Fresh.M4ZoneAssembly.zchunk_of_blocks)
Group files (grp_v_w, gok_v_w) and Fresh/M4ZoneFinal.lean are as in v1-v3.
"""
import json, os, sys
from m4_zone_lean_gen_v1 import ROOT, gen, m4 as m4_v1
from m4_zone_lean_gen_v3 import enc, dec, isChain
from m4_zone_cert_v1 import size

BUDGET = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
HDR = ["namespace Fresh.M4ZoneChunks", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly", ""]

def m4():
    m4_v1()
    certs = {}
    for l in open('m4_zone_certs_v1.jsonl'):
        r = json.loads(l); certs[tuple(r['l'])] = r['tree']
    os.makedirs(f'{ROOT}/M4ZoneChunks/C', exist_ok=True)
    nC = nB = 0
    for v in range(1, 18):
        for w in range(v, 18):
            names = []
            for x in range(w, 18):
                nm = f"{v}_{w}_{x}"
                blocks, cur, curn = [], [], 0
                for t in gen(3, x):
                    tr = certs[tuple([1, v, w, x] + t)]
                    if tr == ["L", []]:
                        assert isChain([1, v, w, x] + t), (v, w, x, t)
                        e, n = [], 1
                    else:
                        e = enc(tr, []); back, k = dec(e)
                        assert k == len(e) and json.dumps(back) == json.dumps(tr), (v, w, x, t)
                        n = size(tr)
                    if cur and curn + n > BUDGET:
                        blocks.append(cur); cur, curn = [], 0
                    cur.append((t, e)); curn += n
                blocks.append(cur)
                out = ["import Fresh.ZoneBlocks", "",
                       f"/-! M4 zone certificates, chunk (v,w,x) = ({v},{w},{x}), {len(blocks)} block(s) of at most {BUDGET} nodes (generated by experiments/n8/m4_zone_lean_gen_v4.py). -/", ""] + HDR
                for k, B in enumerate(blocks):
                    out.append(f"def b_{nm}_{k} : List (List ℕ × List ℕ) := [" + ",\n  ".join(
                        f"([{','.join(map(str, t))}], [{','.join(map(str, e))}])" for t, e in B) + "]")
                    out.append(f"theorem zb_{nm}_{k} : zblk {v} {w} {x} b_{nm}_{k} = true := by decide +kernel")
                    out.append("")
                out.append(f"def L_{nm} : List (List ℕ × List ℕ) := " + " ++ ".join(f"b_{nm}_{k}" for k in range(len(blocks))))
                out.append(f"def cs_{nm} : List ZT := L_{nm}.map (fun p => ZT.dec1 p.2)")
                out.append(f"theorem hg_{nm} : gen 3 {x} = L_{nm}.map Prod.fst := by decide +kernel")
                out.append(f"theorem z_{nm} : zchunk {v} {w} {x} cs_{nm} = true :=")
                out.append(f"  zchunk_of_blocks {v} {w} {x} L_{nm} hg_{nm} (by simp only [L_{nm}, zblk_append, " +
                           ", ".join(f"zb_{nm}_{k}" for k in range(len(blocks))) + ", Bool.and_self])")
                out += ["", "end Fresh.M4ZoneChunks"]
                open(f'{ROOT}/M4ZoneChunks/C/C_{nm}.lean', 'w').write("\n".join(out) + "\n")
                names.append((x, nm)); nC += 1; nB += len(blocks)
            out = ["import Fresh.M4ZoneAssembly"] + [f"import Fresh.M4ZoneChunks.C.C_{nm}" for _, nm in names] + ["",
                   f"/-! M4 zone certificates, group (v,w) = ({v},{w}) (generated by experiments/n8/m4_zone_lean_gen_v4.py). -/", ""] + HDR
            out.append(f"def grp_{v}_{w} : List ((ℕ × ℕ × ℕ) × List ZT) := [" + ", ".join(f"(({v}, {w}, {x}), cs_{nm})" for x, nm in names) + "]")
            out.append(f"theorem gok_{v}_{w} : grp_{v}_{w}.all (fun q => zchunk q.1.1 q.1.2.1 q.1.2.2 q.2) = true := by")
            out.append(f"  simp only [grp_{v}_{w}, List.all_cons, List.all_nil, Bool.and_true, " + ", ".join(f"z_{nm}" for _, nm in names) + "]")
            out += ["", "end Fresh.M4ZoneChunks"]
            open(f'{ROOT}/M4ZoneChunks/G_{v}_{w}.lean', 'w').write("\n".join(out) + "\n")
    print("chunk files", nC, "blocks", nB, "budget", BUDGET)

if __name__ == "__main__":
    m4()
