"""E664 generator (v2: the trailing gap (last component end, 1] is emitted too; v1 left it out): Lean cell theorems for the gap edge of the two-block template, one family (p, P/Q).
Component cells (tau0 in a component [a, c] of K'(r) within [0, 1)): isolated at t0 = N + tau0 for every N = r + Q m.
Gap cells (tau0 in [e, a] before a component): isolated at T = midpoint of the next component of positive length, for
N >= Nmin, Nmin = ceil(T / (8 mu)), mu = least upper margin of the other readings at T (at most 3/4 for the gap
neighbour). Band indices W are chosen here and checked exactly at both ends of each interval (all phases are
increasing linear functions of tau0); Lean re-checks every inequality. Usage: p P Q outfile."""
import sys, math
from fractions import Fraction as F
sys.argv_ = sys.argv
src = open('two_block_cells_v2.py').read().split('fams = [')[0]
ns = {}; exec(compile(src, 'm', 'exec'), ns); Kprime = ns['Kprime']
E = F(1, 8)
p, P, Q, out = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
b = F(P, Q); q = 8 - p
def fl(x): return str(x.numerator) + "/" + str(x.denominator) if x.denominator != 1 else str(x.numerator)
def L(x): return "(%s : ℝ)" % fl(x)
lines = ["import Fresh.TwoBlockGapEdge", "",
         "/-! Generated by experiments/n8/gen_two_block_cells_lean_v1.py (log E664): cell theorems at the gap edge for",
         "p = %d, b = %d/%d, subject p-1. Component cells: isolated at t0 = N + τ0 for every N = r + %d m. Gap cells:" % (p, P, Q, Q),
         "isolated at N + T (T a named point of the next component) for N above an explicit bound. These name an",
         "isolated instant; they do not state that it is the first one. -/",
         "namespace Fresh.TwoBlockGapEdgeCells_p%d_%d_%d" % (p, P, Q), "open Fresh Fresh.TwoBlockGapEdge", "",
         "theorem shift_le {G N τ0 T μ : ℝ} (hτ : 0 ≤ τ0) (hT : τ0 ≤ T) (hNp : 0 < N) (hN : T ≤ 8 * μ * N)",
         "    (hG : G * (N + τ0) = 1/8) : 0 ≤ G * (T - τ0) ∧ G * (T - τ0) ≤ μ := by",
         "  have hpos : 0 < N + τ0 := by linarith",
         "  have hGe : G = 1 / (8 * (N + τ0)) := by field_simp; linarith",
         "  have hG0 : 0 < G := by rw [hGe]; positivity",
         "  refine ⟨mul_nonneg hG0.le (by linarith), ?_⟩",
         "  have h1 : G * (T - τ0) ≤ G * T := by nlinarith",
         "  have h2 : G * T * (8 * (N + τ0)) = T := by rw [hGe]; field_simp",
         "  have h3 : G * T * (8 * N) ≤ T := by nlinarith",
         "  have h4 : G * T ≤ μ := by",
         "    by_contra hc; push_neg at hc",
         "    have : μ * (8 * N) < G * T * (8 * N) := by nlinarith",
         "    nlinarith",
         "  linarith", ""]
def own_band(j, lo, hi):
    W = math.floor(j * (lo + hi) / 2)
    assert W + E <= j * lo and j * hi <= W + 7 * E, (j, lo, hi)
    return W
def oth_val(i, r, T): return E + i * b * (r + T)
def oth_band(i, r, lo, hi, upmargin=F(0)):
    W = math.floor(oth_val(i, r, (lo + hi) / 2))
    assert W + E <= oth_val(i, r, lo) and oth_val(i, r, hi) <= W + 7 * E - upmargin, (i, r, lo, hi)
    return W
bval = "((%d : ℕ) : ℝ) / ((%d : ℕ) : ℝ)" % (P, Q)
nthm = 0; names = []
for r in range(Q):
    comps = [(a, c) for a, c in Kprime(p, b, r, F(0), F(8)) if a < 1]
    allc = Kprime(p, b, r, F(0), F(8))
    prev = F(0)
    for idx, (a, c) in enumerate(comps):
        c1 = min(c, F(1))
        # component cell
        Wo = [own_band(j, a, c1) for j in range(1, p)]
        Wi = [oth_band(i, r, a, c1) for i in range(q)]
        nm = "comp_r%d_%d" % (r, idx); names.append(nm); nthm += 1
        lines += ["/-- τ0 ∈ [%s, %s], r = %d: isolated at t0 = N + τ0. -/" % (fl(a), fl(c1), r),
                  "theorem %s (c G τ0 : ℝ) (m : ℕ) (hlo : %s ≤ τ0) (hhi : τ0 ≤ %s)" % (nm, L(a), L(c1)),
                  "    (hG : G * (((%d + %d * m : ℕ) : ℝ) + τ0) = 1/8) :" % (r, Q),
                  "    IsolatedAt (Fresh.UnequalAPArrangement.speeds c (((%d - 1 : ℕ) : ℝ) + G) 1 (%s) %d) ⟨%d - 1, by omega⟩" % (p, bval, p, p),
                  "      (((%d + %d * m : ℕ) : ℝ) + τ0) := by" % (r, Q),
                  "  apply gapEdge_isolatedAt c _ G _ %d (by norm_num) (by norm_num)" % p,
                  "  · intro j hj1 hj; interval_cases j <;> rw [own_phase]"]
        for j, W in zip(range(1, p), Wo):
            lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by push_cast; linarith) (by push_cast; linarith)" % W)
        lines.append("  · intro i hi; interval_cases i <;> rw [other_phase %d %d %d m _ (by norm_num) _ rfl hG] <;> simp only [sub_self, mul_zero, add_zero]" % (P, Q, r))
        for i, W in zip(range(q), Wi):
            lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by push_cast; linarith) (by push_cast; linarith)" % W)
        lines.append("")
        # gap cell before this component (prev, a), if nonempty
        if prev < a:
            nxt = next(((x, y) for x, y in allc if x >= a and y > x), None)
            T = (nxt[0] + nxt[1]) / 2
            mu = min([F(3, 4)] + [math.floor(oth_val(i, r, T)) + 7 * E - oth_val(i, r, T) for i in range(1, q)])
            assert mu > 0
            Nmin = math.ceil(T / (8 * mu)) + 1
            mmin = max(0, math.ceil(F(Nmin - r, Q)))
            WoT = [own_band(j, T, T) for j in range(1, p)]
            WiT = [oth_band(i, r, T, T, F(0)) for i in range(q)]
            nm = "gap_r%d_%d" % (r, idx); names.append(nm); nthm += 1
            lines += ["/-- τ0 ∈ [%s, %s], r = %d: isolated at N + %s for m ≥ %d. -/" % (fl(prev), fl(a), r, fl(T), mmin),
                      "theorem %s (c G τ0 : ℝ) (m : ℕ) (hlo : %s ≤ τ0) (hhi : τ0 ≤ %s) (hm : %d ≤ m)" % (nm, L(prev), L(a), mmin),
                      "    (hG : G * (((%d + %d * m : ℕ) : ℝ) + τ0) = 1/8) :" % (r, Q),
                      "    IsolatedAt (Fresh.UnequalAPArrangement.speeds c (((%d - 1 : ℕ) : ℝ) + G) 1 (%s) %d) ⟨%d - 1, by omega⟩" % (p, bval, p, p),
                      "      (((%d + %d * m : ℕ) : ℝ) + %s) := by" % (r, Q, L(T)),
                      "  have hmR : (%d : ℝ) ≤ m := by exact_mod_cast hm" % mmin,
                      "  obtain ⟨hs0, hs1⟩ := shift_le (G := G) (N := ((%d + %d * m : ℕ) : ℝ)) (T := %s) (μ := %s) (by linarith) (by linarith)" % (r, Q, L(T), L(mu)),
                      "    (by push_cast; nlinarith) (by push_cast; nlinarith) hG",
                      "  apply gapEdge_isolatedAt c _ G _ %d (by norm_num) (by norm_num)" % p,
                      "  · intro j hj1 hj; interval_cases j <;> rw [own_phase]"]
            for j, W in zip(range(1, p), WoT):
                lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by norm_num) (by norm_num)" % W)
            lines.append("  · intro i hi; interval_cases i <;> rw [other_phase %d %d %d m _ (by norm_num) _ rfl hG]" % (P, Q, r))
            for i, W in zip(range(q), WiT):
                lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by push_cast; linarith) (by push_cast; linarith)" % W)
            lines.append("")
        prev = c1
    if prev < 1:
        a = F(1); idx = len(comps)
        nxt = next(((x, y) for x, y in allc if x >= prev and y > x and x > prev - F(0)), None)
        nxt = next(((x, y) for x, y in allc if x >= 1 and y > x), None)
        T = (nxt[0] + nxt[1]) / 2
        mu = min([F(3, 4)] + [math.floor(oth_val(i, r, T)) + 7 * E - oth_val(i, r, T) for i in range(1, q)])
        assert mu > 0
        Nmin = math.ceil(T / (8 * mu)) + 1
        mmin = max(0, math.ceil(F(Nmin - r, Q)))
        WoT = [own_band(j, T, T) for j in range(1, p)]
        WiT = [oth_band(i, r, T, T, F(0)) for i in range(q)]
        nm = "gap_r%d_%d" % (r, idx); names.append(nm); nthm += 1
        lines += ["/-- τ0 ∈ [%s, 1], r = %d: isolated at N + %s for m ≥ %d. -/" % (fl(prev), r, fl(T), mmin),
                  "theorem %s (c G τ0 : ℝ) (m : ℕ) (hlo : %s ≤ τ0) (hhi : τ0 ≤ (1 : ℝ)) (hm : %d ≤ m)" % (nm, L(prev), mmin),
                  "    (hG : G * (((%d + %d * m : ℕ) : ℝ) + τ0) = 1/8) :" % (r, Q),
                  "    IsolatedAt (Fresh.UnequalAPArrangement.speeds c (((%d - 1 : ℕ) : ℝ) + G) 1 (%s) %d) ⟨%d - 1, by omega⟩" % (p, bval, p, p),
                  "      (((%d + %d * m : ℕ) : ℝ) + %s) := by" % (r, Q, L(T)),
                  "  have hmR : (%d : ℝ) ≤ m := by exact_mod_cast hm" % mmin,
                  "  obtain ⟨hs0, hs1⟩ := shift_le (G := G) (N := ((%d + %d * m : ℕ) : ℝ)) (T := %s) (μ := %s) (by linarith) (by linarith)" % (r, Q, L(T), L(mu)),
                  "    (by push_cast; nlinarith) (by push_cast; nlinarith) hG",
                  "  apply gapEdge_isolatedAt c _ G _ %d (by norm_num) (by norm_num)" % p,
                  "  · intro j hj1 hj; interval_cases j <;> rw [own_phase]"]
        for j, W in zip(range(1, p), WoT):
            lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by norm_num) (by norm_num)" % W)
        lines.append("  · intro i hi; interval_cases i <;> rw [other_phase %d %d %d m _ (by norm_num) _ rfl hG]" % (P, Q, r))
        for i, W in zip(range(q), WiT):
            lines.append("    · exact Fresh.Localisation.clear_of_window (%d) (by push_cast; linarith) (by push_cast; linarith)" % W)
        lines.append("")
lines += ["#print axioms %s" % n for n in names]
lines.append("end Fresh.TwoBlockGapEdgeCells_p%d_%d_%d" % (p, P, Q))
open(out, 'w').write("\n".join(lines) + "\n")
print("theorems:", nthm)
