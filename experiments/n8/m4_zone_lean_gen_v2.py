"""m4_zone_lean_gen_v2 -- M4 zone certificates, one Lean file per chunk (v,w,x).

v1 wrote one file per group (v,w); the four largest (0.77 to 1.19 MB) reached 13 to 14 GB each
under `lean` and exhausted swap at P=4 (2026-11-22).  v2 writes
  Fresh/M4ZoneChunks/C/C_v_w_x.lean : cs_v_w_x and z_v_w_x : zchunk v w x cs_v_w_x = true (decide +kernel)
  Fresh/M4ZoneChunks/G_v_w.lean     : imports its C files; grp_v_w and gok_v_w (as in v1)
  Fresh/M4ZoneFinal.lean            : unchanged from v1 (written by v1's m4()).
Certificates and statements are identical to v1; only the file split changes.
"""
import json, os
from m4_zone_cert_v1 import to_lean
from m4_zone_lean_gen_v1 import ROOT, gen, m4 as m4_v1

HDR = ["namespace Fresh.M4ZoneChunks", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly", ""]

def m4():
    m4_v1()   # writes M4ZoneFinal.lean (and v1 group files, overwritten below)
    certs = {}
    for l in open('m4_zone_certs_v1.jsonl'):
        r = json.loads(l); certs[tuple(r['l'])] = r['tree']
    os.makedirs(f'{ROOT}/M4ZoneChunks/C', exist_ok=True)
    nC = 0
    for v in range(1, 18):
        for w in range(v, 18):
            names = []
            for x in range(w, 18):
                nm = f"{v}_{w}_{x}"
                cs = [to_lean(certs[tuple([1, v, w, x] + t)]) for t in gen(3, x)]
                out = ["import Fresh.M4ZoneAssembly", "",
                       f"/-! M4 zone certificates, chunk (v,w,x) = ({v},{w},{x}) (generated by experiments/n8/m4_zone_lean_gen_v2.py). -/", ""] + HDR
                out.append(f"def cs_{nm} : List ZT := [" + ",\n  ".join(cs) + "]")
                out.append(f"theorem z_{nm} : zchunk {v} {w} {x} cs_{nm} = true := by decide +kernel")
                out += ["", "end Fresh.M4ZoneChunks"]
                open(f'{ROOT}/M4ZoneChunks/C/C_{nm}.lean', 'w').write("\n".join(out) + "\n")
                names.append((x, nm)); nC += 1
            out = ["import Fresh.M4ZoneAssembly"] + [f"import Fresh.M4ZoneChunks.C.C_{nm}" for _, nm in names] + ["",
                   f"/-! M4 zone certificates, group (v,w) = ({v},{w}) (generated by experiments/n8/m4_zone_lean_gen_v2.py). -/", ""] + HDR
            out.append(f"def grp_{v}_{w} : List ((ℕ × ℕ × ℕ) × List ZT) := [" + ", ".join(f"(({v}, {w}, {x}), cs_{nm})" for x, nm in names) + "]")
            out.append(f"theorem gok_{v}_{w} : grp_{v}_{w}.all (fun q => zchunk q.1.1 q.1.2.1 q.1.2.2 q.2) = true := by")
            out.append(f"  simp only [grp_{v}_{w}, List.all_cons, List.all_nil, Bool.and_true, " + ", ".join(f"z_{nm}" for _, nm in names) + "]")
            out += ["", "end Fresh.M4ZoneChunks"]
            open(f'{ROOT}/M4ZoneChunks/G_{v}_{w}.lean', 'w').write("\n".join(out) + "\n")
    print("chunk files", nC)

if __name__ == "__main__":
    m4()
