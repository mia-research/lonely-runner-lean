#!/usr/bin/env python3
"""bandrep_bulktab_v1.py -- the COMPRESSED-TEMPLATE emitter for the [25,29) bulk
(Track B, sub-deliverable A).

Reads `bandrep_r0_redump_25_29_v1.jsonl` (the E916-validated exact re-dump WITH
records, from bandrep_r0dump_v1.py) and emits the decide-backed table files:

  mode t1    -> Fresh/BandReplayBulkT1.lean           (1,000-row sizing tranche;
              measured compile rate extrapolates the full table)
  mode full  -> Fresh/BandReplayBulkCompressed.lean   (ALL rho1-pinned-valid rows,
              per-k7 chunks, per-chunk kernel decide, the appended-table totality,
              and the InBulkBand tuple-membership form)

Both consume the hand-written core `Fresh/BandReplayBulkCore.lean` (rowOK / rowOKB /
certOfRow / bandBulk_of_rowOK).  The per-row certificate condition is discharged ONCE
per chunk by kernel `decide` over the Bool bridge `rowOKB` — the MechDataBatch
M4ResData pattern — replacing the per-box-instance emission whose faithful projection
was ~70 h (E916).  New-file discipline: sibling script, emits only
Fresh/BandReplay*.lean; edits nothing existing.  All arithmetic exact.
"""
import json, os, sys, time
from collections import Counter

N8 = os.path.dirname(os.path.abspath(__file__))
FRESH = os.path.join(os.path.dirname(os.path.dirname(N8)), "LonelyRunnerFresh", "Fresh")
BASE = 1 << 20


def load_valid():
    """All rho1-pinned-valid records in sweep order, split by k7."""
    by_k7 = {25: [], 26: [], 27: [], 28: []}
    n_tot = 0
    with open(os.path.join(N8, "bandrep_r0_redump_25_29_v1.jsonl")) as f:
        for line in f:
            d = json.loads(line)
            n_tot += 1
            if BASE <= d["r"] <= 7 * BASE:      # the rho1-pinned-valid rows
                by_k7[d["k"][5]].append(d)
    return by_k7, n_tot


def row_lit(d):
    k, j, r = d["k"], d["j"], d["r"]
    return "⟨%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d⟩" % (
        k[0], k[1], k[2], k[3], k[4], k[5], r, j[0], j[1], j[2], j[3], j[4], j[5])


def emit_rows(out, rows, indent="  "):
    push = lambda txt: out(txt)
    for i in range(0, len(rows), 4):
        chunk = ", ".join(row_lit(d) for d in rows[i:i + 4])
        push(indent + chunk + ",")


def emit_t1(rows):
    """The 1,000-row sizing tranche."""
    chosen = rows[:1000]
    L = []
    A = L.append
    A("import Fresh.BandReplayBulkCore")
    A("")
    A("/-!")
    A("# The band-bulk compressed template: 1,000-row SIZING TRANCHE (Track B)")
    A("")
    A("Generated by `experiments/n8/bandrep_bulktab_v1.py` (mode t1) from the")
    A("rho1-pinned-valid rows of `bandrep_r0_redump_25_29_v1.jsonl` (the exact E916")
    A("r0 instrument re-dump WITH records; sweep order preserved).  Purpose: the")
    A("compile-RATE measurement that extrapolates the full")
    A("`Fresh/BandReplayBulkCompressed.lean` table against E916's 70 h per-box")
    A("projection.  The per-row certificate condition is discharged ONCE by kernel")
    A("`decide` over the Bool bridge `rowOKB` (the `Fresh.MechDataBatch.M4ResData`")
    A("pattern).  Nothing existing is edited.")
    A("-/")
    A("")
    A("namespace Fresh.BandReplayBulkT1")
    A("")
    A("open Fresh.BandNoCarve")
    A("")
    A("set_option maxRecDepth 800000 in")
    A("/-- The sizing tranche: the first 1,000 rho1-pinned-valid rows in sweep order")
    A("(`k1..k6` = the cells of ρ2..ρ7 at D = 1, `r` = the scaled clear point")
    A("(`R0 = r / bulkBASE`), `j1..j6` = the per-reading gap indices). -/")
    A("def bulkRowsT1 : List BulkRow := [")
    emit_rows(A, chosen)
    A("]")
    A("")
    A("set_option maxRecDepth 800000 in")
    A("set_option maxHeartbeats 1000000000 in")
    A("/-- THE decide: every row of the tranche satisfies the full seven-reading row")
    A("condition (ρ1 pinned: `R0 ∈ [1,7]` at gap 0; the two integer faces per cell")
    A("reading). -/")
    A("theorem bulkRowsT1_ok : bulkRowsT1.all rowOKB = true := by decide")
    A("")
    A("/-- Membership implies the row condition (the decide-backed bridge). -/")
    A("theorem rowOK_of_memT1 {row : BulkRow} (hmem : row ∈ bulkRowsT1) : rowOK row :=")
    A("  (rowOKB_iff row).mp (List.all_eq_true.mp bulkRowsT1_ok row hmem)")
    A("")
    A("/-- **The compressed tranche theorem**: any row of the table certifies every")
    A("arrangement in its cell box (schema class 1, `BandFixedR0`). -/")
    A("theorem bandBulkT1 {row : BulkRow} (hmem : row ∈ bulkRowsT1) {g : Fin 7 → ℝ}")
    A("    (hbox : ∀ i, rowLo row i ≤ g i ∧ g i ≤ rowHi row i) : BandFixedR0 g :=")
    A("  bandBulk_of_rowOK row (rowOK_of_memT1 hmem) hbox")
    A("")
    d0 = chosen[0]
    A("/-- The worked example (the tranche's first row): the row condition decided at")
    A("the Prop level. -/")
    A("theorem worked_rowOK : rowOK %s := by decide" % row_lit(d0))
    A("")
    A("/-- The worked example's consumption: every arrangement in its cell box is")
    A("`BandFixedR0`. -/")
    A("theorem bandBulk_worked {g : Fin 7 → ℝ}")
    A("    (hbox : ∀ i, rowLo %s i ≤ g i ∧ g i ≤ rowHi %s i) : BandFixedR0 g :=" % (
        row_lit(d0), row_lit(d0)))
    A("  bandBulk_of_rowOK _ worked_rowOK hbox")
    A("")
    A("#print axioms bulkRowsT1_ok")
    A("#print axioms rowOK_of_memT1")
    A("#print axioms bandBulkT1")
    A("#print axioms worked_rowOK")
    A("#print axioms bandBulk_worked")
    A("")
    A("end Fresh.BandReplayBulkT1")
    out_path = os.path.join(FRESH, "BandReplayBulkT1.lean")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    return out_path, len(chosen)


def emit_full(by_k7):
    """The full compressed table: per-k7 chunks + totality + tuple-membership form."""
    all_rows = by_k7[25] + by_k7[26] + by_k7[27] + by_k7[28]
    L = []
    A = L.append
    A("import Fresh.BandReplayBulkCore")
    A("")
    A("/-!")
    A("# The band-bulk compressed template: the FULL [25,29) table (Track B)")
    A("")
    A("Generated by `experiments/n8/bandrep_bulktab_v1.py` (mode full) from")
    A("`bandrep_r0_redump_25_29_v1.jsonl`: all %d rho1-pinned-valid rows of the" % len(all_rows))
    A("exact E916 r0 re-dump (555,170 roots reproduced bit-for-bit; 83,641 have")
    A("`R0 ∈ [1,7]` and are `BandFixedR0` certificates under the E832 pinned-ρ1")
    A("convention; the other 471,529 have `R0 < 1` and certify nothing for the pinned")
    A("reading — the honest split of the re-dump).  Per-k7 chunks, one kernel `decide`")
    A("per chunk over `rowOKB` (the MechDataBatch pattern), the appended-table")
    A("totality, and the tuple-membership form `bandBulk_25_29`.  Nothing existing is")
    A("edited.")
    A("-/")
    A("")
    A("namespace Fresh.BandReplayBulkCompressed")
    A("")
    A("open Fresh.BandNoCarve")
    A("")
    SEG = 2000
    seg_oks = {}
    for k7 in (25, 26, 27, 28):
        rows = by_k7[k7]
        segs = [rows[i:i + SEG] for i in range(0, len(rows), SEG)]
        seg_oks[k7] = []
        for si, seg in enumerate(segs):
            A("set_option maxRecDepth 800000 in")
            A("set_option maxHeartbeats 1000000000 in")
            A("/-- The band's k7 = %d rows, segment %d of %d (%d rows, sweep order)." % (
                k7, si, len(segs), len(seg)))
            A("Segments are 2,000-row decided units: the kernel `decide` recursion for")
            A("`List.all` over the whole band overflows the native stack at the")
            A("16,601-27,924-row scale (measured), so the per-segment decide is the")
            A("working granularity — the `List.all_append` composition lifts them. -/")
            A("def bulkSeg_%d_%d : List BulkRow := [" % (k7, si))
            emit_rows(A, seg)
            A("]")
            A("")
            A("set_option maxRecDepth 800000 in")
            A("set_option maxHeartbeats 1000000000 in")
            A("theorem bulkSeg_%d_%d_ok : bulkSeg_%d_%d.all rowOKB = true := by decide" % (
                k7, si, k7, si))
            A("")
            seg_oks[k7].append("bulkSeg_%d_%d_ok" % (k7, si))
        A("/-- The band's k7 = %d rows: the %d decided segments, appended (%d rows" % (
            k7, len(segs), len(rows)))
        A("total). -/")
        A("def bulkRows_%d : List BulkRow := %s" % (
            k7, " ++ ".join("bulkSeg_%d_%d" % (k7, si) for si in range(len(segs)))))
        A("")
        A("set_option maxHeartbeats 1000000000 in")
        A("theorem bulkRows_%d_ok : bulkRows_%d.all rowOKB = true := by" % (k7, k7))
        A("  simp only [bulkRows_%d, List.all_append, %s, Bool.and_true]" % (
            k7, ", ".join(seg_oks[k7])))
        A("")
    A("/-- The full compressed table. -/")
    A("def bulkTable : List BulkRow :=")
    A("  bulkRows_25 ++ bulkRows_26 ++ bulkRows_27 ++ bulkRows_28")
    A("")
    A("/-- THE totality: every row of the full table satisfies the row condition —")
    A("decided per chunk, composed over the append. -/")
    A("theorem bulkTable_ok : bulkTable.all rowOKB = true :=")
    A("  by simp only [bulkTable, List.all_append, bulkRows_25_ok, bulkRows_26_ok,")
    A("      bulkRows_27_ok, bulkRows_28_ok, Bool.and_true]")
    A("")
    A("/-- Membership implies the row condition. -/")
    A("theorem rowOK_of_mem {row : BulkRow} (hmem : row ∈ bulkTable) : rowOK row :=")
    A("  (rowOKB_iff row).mp (List.all_eq_true.mp bulkTable_ok row hmem)")
    A("")
    A("/-- **The compressed band-bulk theorem (row form)**: any row of the table")
    A("certifies every arrangement in its cell box. -/")
    A("theorem bandBulk_25_29_rows {row : BulkRow} (hmem : row ∈ bulkTable)")
    A("    {g : Fin 7 → ℝ}")
    A("    (hbox : ∀ i, rowLo row i ≤ g i ∧ g i ≤ rowHi row i) : BandFixedR0 g :=")
    A("  bandBulk_of_rowOK row (rowOK_of_mem hmem) hbox")
    A("")
    A("/-- The table membership, as a cell-tuple + clear-point lookup (the")
    A("task-suggested `InBulkBand` form). -/")
    A("def InBulkBand (k : Fin 7 → ℤ) (r : ℤ) : Prop :=")
    A("  ∃ row : BulkRow, row ∈ bulkTable ∧ rowK row = k ∧ row.r = r")
    A("")
    A("/-- The upper cell tuple is `rowK + 1` off the pinned index (used to transfer")
    A("the caller's cell-box faces onto the row's faces). -/")
    A("theorem rowHiK_succ (row : BulkRow) (i : Fin 7) (hi : i.val ≠ 0) :")
    A("    rowHiK row i = rowK row i + 1 := by")
    A("  fin_cases i")
    A("  · exact absurd rfl hi")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("  · simp [rowHiK, rowK, Matrix.cons_val_zero, Matrix.cons_val_succ]")
    A("")
    A("/-- **The compressed band-bulk theorem (tuple-membership form)**: a cell tuple")
    A("and clear point in the table certify every arrangement in the tuple's cell box")
    A("with ρ1 pinned to 1 (the pinned seventh reading is the certificate's own face).")
    A("The per-root certificate was decided once for the whole table, not per box —")
    A("the compression that replaces E916's ~70 h per-box projection. -/")
    A("theorem bandBulk_25_29 {k : Fin 7 → ℤ} {r : ℤ} (hmem : InBulkBand k r)")
    A("    {g : Fin 7 → ℝ}")
    A("    (hbox : ∀ i, ((k i : ℤ) : ℝ) ≤ g i ∧ g i ≤ (((k i + 1 : ℤ) : ℝ)))")
    A("    (hp : g 0 = 1) : BandFixedR0 g := by")
    A("  obtain ⟨row, hmemT, hkr, -⟩ := hmem")
    A("  refine bandBulk_of_rowOK row (rowOK_of_mem hmemT) ?_")
    A("  intro i")
    A("  have hi0 : i.val ≠ 0 ∨ i.val = 0 := by omega")
    A("  rcases hi0 with hi | hi")
    A("  · have hhi : rowHiK row i = rowK row i + 1 := rowHiK_succ row i hi")
    A("    rw [show rowLo row i = ((rowK row i : ℤ) : ℝ) from rfl,")
    A("        show rowHi row i = ((rowHiK row i : ℤ) : ℝ) from rfl, hhi, hkr]")
    A("    exact hbox i")
    A("  · have hi0 : i = 0 := by omega")
    A("    subst hi0")
    A("    norm_num [rowLo, rowHi, rowK, rowHiK, Matrix.cons_val_zero,")
    A("      Matrix.cons_val_succ, hp]")
    A("")
    A("#print axioms bulkRows_25_ok")
    A("#print axioms bulkRows_26_ok")
    A("#print axioms bulkRows_27_ok")
    A("#print axioms bulkRows_28_ok")
    A("#print axioms bulkTable_ok")
    A("#print axioms rowOK_of_mem")
    A("#print axioms bandBulk_25_29_rows")
    A("#print axioms bandBulk_25_29")
    A("")
    A("end Fresh.BandReplayBulkCompressed")
    out_path = os.path.join(FRESH, "BandReplayBulkCompressed.lean")
    with open(out_path, "w") as f:
        f.write("\n".join(L) + "\n")
    return out_path, len(all_rows)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "t1"
    t0 = time.time()
    by_k7, n_tot = load_valid()
    n_valid = sum(len(v) for v in by_k7.values())
    print(f"re-dump: {n_tot} certified roots, {n_valid} rho1-pinned-valid "
          f"(per k7: { {k: len(v) for k, v in sorted(by_k7.items())} })")
    if mode == "t1":
        out_path, n = emit_t1(by_k7[25] + by_k7[26] + by_k7[27] + by_k7[28])
    elif mode == "full":
        out_path, n = emit_full(by_k7)
    else:
        sys.exit("unknown mode (t1 | full)")
    print(f"emitted {n} rows -> {out_path}  ({time.time()-t0:.1f} s)")


if __name__ == "__main__":
    main()
