# widthemiss_gen_v1 -- emit the per-class width facts into Lean:
# per class k: theorem wfact_k : (2:ℚ)/25 ≤ B_k - A_k := by norm_num  (the exact ℚ width check)
# grouped into chunk files of 1,000 classes (compile-time control).
# The composition: colDead50_of_width A B hA hB wfact_k gives the class's column death
# in closed form — no probe-evidence dependency, no race machinery.
import json

data = json.load(open('/Users/trentpalelei/Desktop/Math Ex/experiments/n8/widthpass_v1.json'))
all_cls = data['width_closed']
print(f'width-closed classes: {len(all_cls)}')

def skel_str(skel):
    return '_'.join(str(x) for x in skel)

CHUNK = 1000
n_chunks = (len(all_cls) + CHUNK - 1) // CHUNK
header = """import Mathlib.Tactic
import Fresh.WidthCert

/-!
# Per-class width facts for the chamber datasheet classes (width-closed tranche)

Per class: the recorded component (A, B) has width B - A >= 2/25, so
`Fresh.WidthCert.colDead50_of_width` gives the column-death certificate in closed
form (no probe-evidence dependency, no race machinery).  Generated by
widthemiss_gen_v1.py from widthpass_v1.json (exact Fractions).
-/

namespace Fresh.WidthClosed

"""

footer = """
end Fresh.WidthClosed
"""

for ci in range(n_chunks):
    chunk = all_cls[ci*CHUNK:(ci+1)*CHUNK]
    lines = [header.replace('# Per-class width facts', f'# Per-class width facts, chunk {ci+1}/{n_chunks}')]
    for n, rec in enumerate(chunk):
        gi = ci * CHUNK + n
        skel, kL, kR, cellL, cellR, astr, bstr, wstr = rec
        # normalize A, B as exact ℚ literals
        a_frac = json.loads(json.dumps(astr))  # str like "85/76"
        if '/' in astr:
            an, ad = astr.split('/')
            Alit = f'(({int(an):} : \u211a) / {int(ad):})'
        else:
            Alit = f'({int(astr):} : \u211a)'
        if '/' in bstr:
            bn, bd = bstr.split('/')
            Blit = f'(({int(bn):} : \u211a) / {int(bd):})'
        else:
            Blit = f'({int(bstr):} : \u211a)'
        lines.append(f'theorem wfact_{gi} : (2:\u211a) / 25 \u2264 {Blit} - {Alit} := by norm_num')
    lines.append('\nend Fresh.WidthClosed')
    fname = f'/Users/trentpalelei/Desktop/Math Ex/LonelyRunnerFresh/Fresh/WidthClosed_{ci}.lean'
    with open(fname, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {fname}: {len(chunk)} width facts')

print('done')
