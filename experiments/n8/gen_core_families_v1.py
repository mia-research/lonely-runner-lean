# E640: generate Lean for frozen-core families {core of six whole numbers} + one further whole number x, for ALL x >= 1:
#   x >= x0 = ceil(1/(4 w)) (w = widest exact clear window of the core) by CoreFamilies.core_single, x < x0 by an explicit exact rational instant (the cascade landing of the set) checked reading by reading.
# usage: gen_core_families_v1.py out.lean core1 core2 ...   (a core is comma-separated whole numbers, six of them)
import sys, math
from fractions import Fraction as F
E = F(1, 8)
def dist(x): f = x - math.floor(x); return min(f, 1 - f)
def clear_iv(x, T):
    out = []; n = 0
    while True:
        lo = F(8 * n + 1, 8) / x; hi = F(8 * n + 7, 8) / x
        if lo > T: break
        out.append((lo, min(hi, T))); n += 1
    return out
def meet(A, B):
    out = []; i = j = 0
    while i < len(A) and j < len(B):
        lo = max(A[i][0], B[j][0]); hi = min(A[i][1], B[j][1])
        if lo <= hi: out.append((lo, hi))
        if A[i][1] < B[j][1]: i += 1
        else: j += 1
    return out
def widest_window(S):
    g = 0
    for d in S: g = math.gcd(g, d)
    T = F(2, g)
    J = clear_iv(F(S[0]), T)
    for s in S[1:]: J = meet(J, clear_iv(F(s), T))
    return max(J, key=lambda iv: iv[1] - iv[0])
def casc(S):
    t = F(1, 8 * min(S))
    while True:
        way = [d for d in S if dist(d * t) < E]
        if not way: return t
        t = max((F(round(d * t)) + E) / d for d in way)
def fr(q):  # Lean real literal for a Fraction
    return "(%d : ℝ)" % q.numerator if q.denominator == 1 else "((%d : ℝ) / %d)" % (q.numerator, q.denominator)
out = ["import Mathlib", "import Fresh.Framework", "import Fresh.Localisation", "import Fresh.CoreFamilies", "",
       "/-! Generated by experiments/n8/gen_core_families_v1.py (E640).  Frozen-core families: a core of six whole numbers and one further whole number `x`, for every `x ≥ 1`.",
       "For `x ≥ x0` the core's widest exact window and `CoreFamilies.core_single`; for `x < x0` an explicit exact rational instant (the cascade landing), checked reading by reading.  Grade [L].",
       "**[PROVISIONAL: covering]** as in `ClusterWindow`. -/", "", "open Classical", "", "namespace Fresh.%s" % __import__("os").path.basename(sys.argv[1])[:-5], "", "open Fresh Fresh.CoreFamilies", ""]
names = []
for arg in sys.argv[2:]:
    C = [int(x) for x in arg.split(',')]
    assert len(C) == 6 and C == sorted(set(C))
    lo, hi = widest_window(C); w = hi - lo
    x0 = math.ceil(1 / (4 * w))
    tag = "_".join(map(str, C))
    Cl = "({" + ", ".join("(%d : ℝ)" % c for c in C) + "} : Finset ℝ)"
    # certificates for x < x0
    for x in range(1, x0):
        S = sorted(set(C) | {x}); t = casc(S)
        assert all(dist(d * t) >= E for d in S)
        out.append("theorem cert_%s_x%d : ∃ t : ℝ, 0 < t ∧ ∀ d ∈ insert ((%d : ℕ) : ℝ) %s, (1 / 8 : ℝ) ≤ distInt (d * t) := by" % (tag, x, x, Cl))
        out.append("  refine ⟨%s, by norm_num, ?_⟩" % fr(t))
        out.append("  intro d hd")
        out.append("  simp only [Finset.mem_insert, Finset.mem_singleton] at hd")
        vals = [x] + C
        out.append("  rcases hd with " + " | ".join(["rfl"] * 7))
        for v in vals:
            N = math.floor(v * t)
            out.append("  · exact Fresh.Localisation.clear_of_window %d (by norm_num) (by norm_num)" % N)
        out.append("")
    # window bands
    Ns = [math.floor(s * lo - E) for s in C]
    assert all(F(N) + E <= s * lo and s * hi <= F(N) + F(7, 8) for N, s in zip(Ns, C))
    out.append("theorem family_%s (x : ℕ) (hx : 1 ≤ x) : ∃ t : ℝ, 0 < t ∧ ∀ d ∈ insert (x : ℝ) %s, (1 / 8 : ℝ) ≤ distInt (d * t) := by" % (tag, Cl))
    out.append("  by_cases hxx : %d ≤ x" % x0)
    out.append("  · have hxR : (%d : ℝ) ≤ (x : ℝ) := by exact_mod_cast hxx" % x0)
    out.append("    have hxpos : (0 : ℝ) < (x : ℝ) := by linarith [show (0 : ℝ) < %d by norm_num]" % x0)
    out.append("    have hpos : ∀ s ∈ %s, 0 < s := by" % Cl)
    out.append("      intro s hs")
    out.append("      simp only [Finset.mem_insert, Finset.mem_singleton] at hs")
    out.append("      rcases hs with " + " | ".join(["rfl"] * 6) + " <;> norm_num")
    out.append("    have hb : ∀ s ∈ %s, ∃ N : ℤ, (N : ℝ) + 1 / 8 ≤ s * %s ∧ s * %s ≤ (N : ℝ) + 7 / 8 := by" % (Cl, fr(lo), fr(hi)))
    out.append("      intro s hs")
    out.append("      simp only [Finset.mem_insert, Finset.mem_singleton] at hs")
    out.append("      rcases hs with " + " | ".join(["rfl"] * 6))
    for N in Ns: out.append("      · exact ⟨%d, by norm_num, by norm_num⟩" % N)
    out.append("    have hgap : 1 / (4 * (x : ℝ)) ≤ %s - %s := by" % (fr(hi), fr(lo)))
    out.append("      rw [show %s - %s = %s by norm_num, div_le_iff₀ (by positivity)]" % (fr(hi), fr(lo), fr(w)))
    out.append("      nlinarith")
    out.append("    obtain ⟨t, ht, hS, hx'⟩ := core_single (lo := %s) (hi := %s) (x := (x : ℝ)) (S := %s) (by norm_num) hpos hb hxpos hgap" % (fr(lo), fr(hi), Cl))
    out.append("    refine ⟨t, ht, fun d hd => ?_⟩")
    out.append("    rcases Finset.mem_insert.1 hd with rfl | hd'")
    out.append("    · exact hx'")
    out.append("    · exact hS d hd'")
    out.append("  · push Not at hxx")
    out.append("    interval_cases x")
    for x in range(1, x0): out.append("    · exact cert_%s_x%d" % (tag, x))
    out.append("")
    names.append((tag, x0, w))
out.append("end Fresh.%s" % __import__("os").path.basename(sys.argv[1])[:-5])
open(sys.argv[1], "w").write("\n".join(out) + "\n")
for tag, x0, w in names: print(tag, "x0", x0, "w", w)
