#!/usr/bin/env python3
"""m4_zone_lean_gen_v1 -- write the Lean certificate files for the zone route.

chain : Fresh/ChainZone/S_k.lean (per-box theorems cz_i : zc 1 cert_i (rootZ (boxOfL
        ((1::t).map Int.toNat) 0)) = true, by decide +kernel), and Fresh/ChainZoneFinal.lean
        (ChainBoxSoundPinned via chainPinned_of_zone, case split over chainBoxes).
m4    : Fresh/M4ZoneChunks/G_v_w.lean (per chunk (v,w,x): cs_v_w_x and z_v_w_x : zchunk v w x
        cs_v_w_x = true by decide +kernel; group list grp_v_w and gok_v_w), and
        Fresh/M4ZoneFinal.lean (M4BoxNoCarvePinned via m4Pinned_of_zchunks)."""
import sys, json, os
sys.path.insert(0, '.')
from m4_zone_cert_v1 import to_lean
ROOT = '../../LonelyRunnerFresh/Fresh'

def chain():
    rows = [json.loads(l) for l in open('m4_zone_certs_chain_v1.jsonl')]
    os.makedirs(f'{ROOT}/ChainZone', exist_ok=True)
    K = 8; per = (len(rows) + K - 1) // K
    for k in range(K):
        sl = list(enumerate(rows))[k * per:(k + 1) * per]
        out = ["import Fresh.M4ZoneAssembly", "",
               f"/-! Chain-box zone certificates, slice {k} (generated by experiments/n8/m4_zone_lean_gen_v1.py). -/", "",
               "namespace Fresh.ChainZone", "open Fresh.ZoneCover Fresh.M4SplitAssembly", ""]
        for i, r in sl:
            t = r['t']
            out.append(f"def cc_{i} : ZT := {to_lean(r['tree'])}")
            out.append(f"theorem cz_{i} : zc 1 cc_{i} (rootZ (boxOfL (((1 : ℤ) :: {t}).map Int.toNat) 0)) = true := by")
            out.append("  decide +kernel")
            out.append("")
        out.append("end Fresh.ChainZone")
        open(f'{ROOT}/ChainZone/S_{k}.lean', 'w').write("\n".join(out) + "\n")
    alts = " | ".join(["rfl"] * len(rows))
    fin = ["import Fresh.M4ZoneAssembly"] + [f"import Fresh.ChainZone.S_{k}" for k in range(K)] + ["",
      "/-!", "# `ChainBoxSoundPinned`, proved (2026-11-22)", "",
      "New file.  The 73 chain boxes, each covered by a gap-pattern zone certificate with `w = 1`",
      "(`Fresh/ChainZone/S_k.lean`, kernel-checked); `chainPinned_of_zone` does the rest.", "",
      "Covering form [PROVISIONAL: covering -- supports \"every reading vector of a chain box has a",
      "clear instant R in [1,7] or [9,15]\"]: each box lies in the union of the gap-pattern zones C_m.",
      "The Lean proof assumes no covering: every cut is a case split by le_total and every leaf is",
      "an exact inclusion.  The place: R = max_r (8 m_r + 1)/g_r, the last gap entry over the readings.", "-/", "",
      "namespace Fresh.ChainZone", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly Fresh.FilterAssemblyPerBox",
      "open Fresh.FilterAssemblyPerBoxV2", "",
      "theorem chainBoxSoundPinned_proved : ChainBoxSoundPinned := by",
      "  refine chainPinned_of_zone ?_",
      "  intro t ht",
      "  simp only [chainBoxes, List.mem_cons, List.not_mem_nil, or_false] at ht",
      f"  rcases ht with {alts}"]
    for i in range(len(rows)):
        fin.append(f"  · exact ⟨_, cz_{i}⟩")
    fin += ["", "#print axioms chainBoxSoundPinned_proved", "", "end Fresh.ChainZone"]
    open(f'{ROOT}/ChainZoneFinal.lean', 'w').write("\n".join(fin) + "\n")
    print("chain files", K, "boxes", len(rows))

def gen(k, lo):
    if k == 0: return [[]]
    return [[v] + t for v in range(lo, 18) for t in gen(k - 1, v)]

def m4():
    certs = {}
    for l in open('m4_zone_certs_v1.jsonl'):
        r = json.loads(l)
        assert 'tree' in r, r
        certs[tuple(r['l'])] = r['tree']
    os.makedirs(f'{ROOT}/M4ZoneChunks', exist_ok=True)
    groups = []
    for v in range(1, 18):
        for w in range(v, 18):
            out = ["import Fresh.M4ZoneAssembly", "",
                   f"/-! M4 zone certificates, chunks (v,w,x) = ({v},{w},x) (generated by experiments/n8/m4_zone_lean_gen_v1.py). -/", "",
                   "namespace Fresh.M4ZoneChunks", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly", ""]
            names = []
            for x in range(w, 18):
                cs = [to_lean(certs[tuple([1, v, w, x] + t)]) for t in gen(3, x)]
                nm = f"{v}_{w}_{x}"
                out.append(f"def cs_{nm} : List ZT := [" + ",\n  ".join(cs) + "]")
                out.append(f"theorem z_{nm} : zchunk {v} {w} {x} cs_{nm} = true := by decide +kernel")
                out.append("")
                names.append((x, nm))
            out.append(f"def grp_{v}_{w} : List ((ℕ × ℕ × ℕ) × List ZT) := [" + ", ".join(f"(({v}, {w}, {x}), cs_{nm})" for x, nm in names) + "]")
            out.append(f"theorem gok_{v}_{w} : grp_{v}_{w}.all (fun q => zchunk q.1.1 q.1.2.1 q.1.2.2 q.2) = true := by")
            out.append(f"  simp only [grp_{v}_{w}, List.all_cons, List.all_nil, Bool.and_true, " + ", ".join(f"z_{nm}" for _, nm in names) + "]")
            out.append("")
            out.append("end Fresh.M4ZoneChunks")
            open(f'{ROOT}/M4ZoneChunks/G_{v}_{w}.lean', 'w').write("\n".join(out) + "\n")
            groups.append((v, w))
    G = " ++ ".join(f"grp_{v}_{w}" for v, w in groups)
    fin = ["import Fresh.M4ZoneAssembly"] + [f"import Fresh.M4ZoneChunks.G_{v}_{w}" for v, w in groups] + ["",
      "/-!", "# `M4BoxNoCarvePinned`, proved (2026-11-22)", "",
      "New file.  Every sorted 7-tuple of `[1,17]^7` containing `1` carries a gap-pattern zone",
      "certificate (`Fresh/M4ZoneChunks/G_v_w.lean`, kernel-checked chunk by chunk), or is a chain",
      "box; `m4Pinned_of_zchunks` does the rest.", "",
      "Covering form [PROVISIONAL: covering -- supports \"every reading vector of an M4 box has a",
      "clear instant R in [1,7]\"]: each box lies in the union of the gap-pattern zones C_m.",
      "The Lean proof assumes no covering: every cut is a case split by le_total and every leaf is",
      "an exact inclusion.  The place: R = max_r (8 m_r + 1)/g_r, the last gap entry over the readings.", "-/", "",
      "namespace Fresh.M4ZoneChunks", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly",
      "open Fresh.FilterAssemblyPerBoxV2", "",
      f"def allC : List ((ℕ × ℕ × ℕ) × List ZT) := {G}", "",
      "theorem allC_ok : allC.all (fun q => zchunk q.1.1 q.1.2.1 q.1.2.2 q.2) = true := by",
      "  simp only [allC, List.all_append, Bool.and_eq_true, " + ", ".join(f"gok_{v}_{w}" for v, w in groups) + ", and_self]", "",
      "theorem trip_eq : trip = allC.map Prod.fst := by decide +kernel", "",
      "theorem m4BoxNoCarvePinned_proved : M4BoxNoCarvePinned := by",
      "  refine m4Pinned_of_zchunks ?_",
      "  intro p hp",
      "  rw [trip_eq, List.mem_map] at hp",
      "  obtain ⟨q, hq, rfl⟩ := hp",
      "  exact ⟨q.2, (List.all_eq_true.mp allC_ok) q hq⟩", "",
      "#print axioms m4BoxNoCarvePinned_proved", "", "end Fresh.M4ZoneChunks"]
    open(f'{ROOT}/M4ZoneFinal.lean', 'w').write("\n".join(fin) + "\n")
    print("m4 group files", len(groups))

if __name__ == "__main__":
    for a in sys.argv[1:]: {"chain": chain, "m4": m4}[a]()
