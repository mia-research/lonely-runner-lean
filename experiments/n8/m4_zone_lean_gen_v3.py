"""m4_zone_lean_gen_v3 -- M4 zone certificates, one Lean file per chunk, flat encoding.

Each tuple's code is its own declaration d_v_w_x_k (one List N literal per heartbeat budget;
a single ds literal per chunk timed out at whnf in C_4_5_6).

v2 (one file per chunk, nested ZT literals) hits the elaborator's heartbeat limit on the larger
chunks (C_4_5_6: deterministic timeout at isDefEq, 2026-11-22).  v3 writes each certificate as a
prefix code in List N (Fresh/ZoneDecode.lean: 0 m0..m6 = leaf, 1 r s p q a b = cut) and sets
cs_v_w_x := ds_v_w_x.map ZT.dec1.  Group files and Fresh/M4ZoneFinal.lean are as in v2/v1.
"""
import json, os, sys
from m4_zone_lean_gen_v1 import ROOT, gen, m4 as m4_v1

def enc(t, out):
    if t[0] == "L":
        assert len(t[1]) == 7, t
        out.append(0); out.extend(t[1])
    else:
        _, r, s, p, q, a, b = t
        out.extend([1, r, s, p, q]); enc(a, out); enc(b, out)
    return out

def dec(l, i=0):   # Python mirror of Fresh.ZoneCover.decT, for a round-trip check
    if l[i] == 0: return ["L", l[i+1:i+8]], i + 8
    r, s, p, q = l[i+1:i+5]
    a, j = dec(l, i + 5); b, k = dec(l, j)
    return ["C", r, s, p, q, a, b], k

def depth(t): return 0 if t[0] == "L" else 1 + max(depth(t[5]), depth(t[6]))

CHAIN = None
def isChain(l):
    global CHAIN
    if CHAIN is None:
        CHAIN = {tuple([1] + json.loads(r)['t']) for r in open('m4_zone_certs_chain_v1.jsonl')}
    return tuple(l) in CHAIN

HDR = ["namespace Fresh.M4ZoneChunks", "open Fresh.ZoneCover Fresh.M4SplitAssembly Fresh.M4ZoneAssembly", ""]

def m4():
    m4_v1()
    certs = {}
    for l in open('m4_zone_certs_v1.jsonl'):
        r = json.loads(l); certs[tuple(r['l'])] = r['tree']
    os.makedirs(f'{ROOT}/M4ZoneChunks/C', exist_ok=True)
    nC = 0; maxd = 0
    for v in range(1, 18):
        for w in range(v, 18):
            names = []
            for x in range(w, 18):
                nm = f"{v}_{w}_{x}"
                ds = []
                for t in gen(3, x):
                    tr = certs[tuple([1, v, w, x] + t)]
                    if tr == ["L", []]:          # chain-box placeholder: dec1 [] = .leaf []
                        assert isChain([1, v, w, x] + t), (v, w, x, t)
                        e = []
                    else:
                        e = enc(tr, [])
                        back, k = dec(e)
                        assert k == len(e) and json.dumps(back) == json.dumps(tr), (v, w, x, t)
                    maxd = max(maxd, depth(tr))
                    ds.append("[" + ",".join(map(str, e)) + "]")
                out = ["import Fresh.M4ZoneAssembly", "import Fresh.ZoneDecode", "",
                       f"/-! M4 zone certificates, chunk (v,w,x) = ({v},{w},{x}), prefix-coded (generated by experiments/n8/m4_zone_lean_gen_v3.py). -/", ""] + HDR
                for k, d in enumerate(ds):      # one declaration per tuple: bounded literal per heartbeat budget
                    out.append(f"def d_{nm}_{k} : List ℕ := {d}")
                out.append(f"def ds_{nm} : List (List ℕ) := [" + ", ".join(f"d_{nm}_{k}" for k in range(len(ds))) + "]")
                out.append(f"def cs_{nm} : List ZT := ds_{nm}.map ZT.dec1")
                out.append(f"theorem z_{nm} : zchunk {v} {w} {x} cs_{nm} = true := by decide +kernel")
                out += ["", "end Fresh.M4ZoneChunks"]
                open(f'{ROOT}/M4ZoneChunks/C/C_{nm}.lean', 'w').write("\n".join(out) + "\n")
                names.append((x, nm)); nC += 1
            out = ["import Fresh.M4ZoneAssembly"] + [f"import Fresh.M4ZoneChunks.C.C_{nm}" for _, nm in names] + ["",
                   f"/-! M4 zone certificates, group (v,w) = ({v},{w}) (generated by experiments/n8/m4_zone_lean_gen_v3.py). -/", ""] + HDR
            out.append(f"def grp_{v}_{w} : List ((ℕ × ℕ × ℕ) × List ZT) := [" + ", ".join(f"(({v}, {w}, {x}), cs_{nm})" for x, nm in names) + "]")
            out.append(f"theorem gok_{v}_{w} : grp_{v}_{w}.all (fun q => zchunk q.1.1 q.1.2.1 q.1.2.2 q.2) = true := by")
            out.append(f"  simp only [grp_{v}_{w}, List.all_cons, List.all_nil, Bool.and_true, " + ", ".join(f"z_{nm}" for _, nm in names) + "]")
            out += ["", "end Fresh.M4ZoneChunks"]
            open(f'{ROOT}/M4ZoneChunks/G_{v}_{w}.lean', 'w').write("\n".join(out) + "\n")
    print("chunk files", nC, "max tree depth", maxd)

if __name__ == "__main__":
    m4()
